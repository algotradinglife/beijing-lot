class ContractError(ValueError):
    """Raised when a source or derived frame violates the frozen contract."""


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def stable_frame_sha(frame: pd.DataFrame) -> str:
    columns = sorted(frame.columns)
    projected = frame.loc[:, columns]
    row_hashes = np.sort(
        pd.util.hash_pandas_object(
            projected,
            index=False,
            categorize=False,
        ).to_numpy(dtype=np.uint64)
    )
    schema = [(column, str(projected[column].dtype)) for column in columns]
    digest = hashlib.sha256(
        json.dumps(schema, separators=(",", ":")).encode("utf-8")
    )
    digest.update(row_hashes.tobytes())
    return digest.hexdigest()


def _verify_proxy_parts(proxy_root: Path) -> str:
    manifest = _read_json(proxy_root / "MANIFEST.json")
    parts = manifest.get("parts")
    if not isinstance(parts, dict) or not parts:
        raise ContractError("proxy manifest has no part hashes")
    consumed = {
        relative: digest
        for relative, digest in parts.items()
        if relative.startswith(("probabilities/", "translation_readiness/"))
    }
    if not consumed:
        raise ContractError("proxy manifest lacks consumed probability parts")
    for relative, expected in sorted(consumed.items()):
        path = proxy_root / relative
        if not path.is_file() or sha256_file(path) != expected:
            raise ContractError(f"proxy source part hash mismatch: {relative}")
    payload = json.dumps(consumed, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def issue_codes_without_a_contract_year(roles: pd.DataFrame) -> list[str]:
    """Return the issue codes whose year did not come from the contract source.

    A named check, not an inline comparison: an example that reads the constant only proves the
    constant exists, while an example that calls this proves the panel actually accepts what the
    producer emits -- the mistake this exists to catch was the comparison and the emitter
    disagreeing on a spelling.
    """
    return roles.loc[
        ~roles["issue_date_source"].eq(SOURCE_ISSUE_DATE_SOURCE), "issue_code"
    ].astype(str).tolist()


def locate_data_root(repo_root: Path, explicit: Path | None = None) -> Path:
    candidates = [] if explicit is None else [Path(explicit)]
    candidates.extend([repo_root / "data", repo_root.parents[1] / "data"])
    required = (
        CANDIDATE_SQLITE_RELATIVE,
        LABEL_SQLITE_RELATIVE,
        ACCEPTED_238_RELATIVE,
    )
    for candidate in candidates:
        if all((candidate / item).exists() for item in required):
            return candidate.resolve()
    raise FileNotFoundError("canonical data root for Issue #354 was not found")


def _connect_read_only(path: Path) -> sqlite3.Connection:
    resolved = path.resolve()
    if not resolved.is_file():
        raise FileNotFoundError(resolved)
    connection = sqlite3.connect(f"file:{resolved}?mode=ro", uri=True)
    connection.execute("PRAGMA query_only=ON")
    return connection


def _fixture_timing(candidate_sqlite: Path) -> pd.DataFrame:
    with _connect_read_only(candidate_sqlite) as connection:
        timing = pd.read_sql_query(
            """
            SELECT CAST(issue_code AS TEXT) AS issue_code, match_idx, kickoff_ts
            FROM inventory
            ORDER BY issue_code, match_idx
            """,
            connection,
        )
    if timing.duplicated(["issue_code", "match_idx"]).any():
        raise ContractError("fixture timing keys are not unique")
    timing["fixture_kickoff_ts"] = pd.to_datetime(
        timing.pop("kickoff_ts"), errors="coerce", utc=True
    )
    valid = timing["fixture_kickoff_ts"].ge(pd.Timestamp("2013-01-01", tz="UTC"))
    timing.loc[~valid, "fixture_kickoff_ts"] = pd.NaT
    timing["fixture_decision_ts"] = timing["fixture_kickoff_ts"] - pd.Timedelta(hours=10)
    timing["label_available_ts"] = timing["fixture_kickoff_ts"] + pd.Timedelta(hours=4)
    return timing


def _model() -> Pipeline:
    numeric = [
        "q_eu_3",
        "q_eu_1",
        "q_eu_0",
        "line_x_q_eu_3",
        "line_x_q_eu_1",
        "line_x_q_eu_0",
    ]
    return Pipeline(
        [
            (
                "features",
                ColumnTransformer(
                    [
                        (
                            "line",
                            OneHotEncoder(handle_unknown="ignore", sparse_output=False),
                            ["native_handicap_line"],
                        ),
                        ("numeric", StandardScaler(), numeric),
                    ],
                    remainder="drop",
                ),
            ),
            (
                "model",
                LogisticRegression(
                    solver="lbfgs",
                    max_iter=1_000,
                    random_state=MODEL_RANDOM_STATE,
                ),
            ),
        ]
    )


def _ordered_probability(model: Pipeline, frame: pd.DataFrame) -> np.ndarray:
    raw = model.predict_proba(frame)
    classes = [str(value) for value in model.named_steps["model"].classes_]
    if set(classes) != set(OUTCOMES):
        raise ContractError(f"model classes differ from {OUTCOMES}: {classes}")
    probability = raw[:, [classes.index(code) for code in OUTCOMES]]
    if not np.isfinite(probability).all() or (probability <= 0).any():
        raise ContractError("model emitted invalid probability cells")
    if not np.allclose(probability.sum(axis=1), 1.0, rtol=0, atol=PROBABILITY_ATOL):
        raise ContractError("model probabilities do not sum to one")
    return probability


