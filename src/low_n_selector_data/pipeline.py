class ContractError(ValueError):
    """Raised when a source or derived frame violates the frozen contract."""


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def stable_frame_sha(frame: pd.DataFrame) -> str:
    columns = sorted(frame.columns)
    ordered = frame.loc[:, columns].sort_values(columns, kind="stable").reset_index(drop=True)
    payload = ordered.to_csv(index=False, lineterminator="\n", float_format="%.17g")
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def locate_data_root(repo_root: Path, explicit: Path | None = None) -> Path:
    candidates = [] if explicit is None else [Path(explicit)]
    candidates.extend([repo_root / "data", repo_root.parents[1] / "data"])
    required = (
        CANDIDATE_SQLITE_RELATIVE,
        ISSUE_REGISTRY_RELATIVE,
        LABEL_SQLITE_RELATIVE,
        ACCEPTED_238_RELATIVE,
    )
    for candidate in candidates:
        if all((candidate / item).exists() for item in required):
            return candidate.resolve()
    raise FileNotFoundError("canonical data root for Issue #354 was not found")


def _connect_read_only(path: Path) -> sqlite3.Connection:
    resolved = path.resolve()
    if not resolved.is_file():
        raise FileNotFoundError(resolved)
    connection = sqlite3.connect(f"file:{resolved}?mode=ro", uri=True)
    connection.execute("PRAGMA query_only=ON")
    return connection


def _model() -> Pipeline:
    numeric = [
        "q_eu_3",
        "q_eu_1",
        "q_eu_0",
        "line_x_q_eu_3",
        "line_x_q_eu_1",
        "line_x_q_eu_0",
    ]
    return Pipeline(
        [
            (
                "features",
                ColumnTransformer(
                    [
                        (
                            "line",
                            OneHotEncoder(handle_unknown="ignore", sparse_output=False),
                            ["native_handicap_line"],
                        ),
                        ("numeric", StandardScaler(), numeric),
                    ],
                    remainder="drop",
                ),
            ),
            (
                "model",
                LogisticRegression(
                    solver="lbfgs",
                    max_iter=1_000,
                    random_state=MODEL_RANDOM_STATE,
                ),
            ),
        ]
    )


def _ordered_probability(model: Pipeline, frame: pd.DataFrame) -> np.ndarray:
    raw = model.predict_proba(frame)
    classes = [str(value) for value in model.named_steps["model"].classes_]
    if set(classes) != set(OUTCOMES):
        raise ContractError(f"model classes differ from {OUTCOMES}: {classes}")
    probability = raw[:, [classes.index(code) for code in OUTCOMES]]
    if not np.isfinite(probability).all() or (probability <= 0).any():
        raise ContractError("model emitted invalid probability cells")
    if not np.allclose(probability.sum(axis=1), 1.0, rtol=0, atol=PROBABILITY_ATOL):
        raise ContractError("model probabilities do not sum to one")
    return probability


def _control_model() -> Pipeline:
    return Pipeline(
        [
            (
                "features",
                ColumnTransformer(
                    [
                        (
                            "line",
                            OneHotEncoder(handle_unknown="ignore", sparse_output=False),
                            ["native_handicap_line"],
                        )
                    ],
                    remainder="drop",
                ),
            ),
            (
                "model",
                LogisticRegression(
                    solver="lbfgs",
                    max_iter=1_000,
                    random_state=MODEL_RANDOM_STATE,
                ),
            ),
        ]
    )


def _input_panel(data_root: Path) -> tuple[pd.DataFrame, pd.DataFrame, dict[str, str]]:
    candidate = data_root / CANDIDATE_SQLITE_RELATIVE
    registry = data_root / ISSUE_REGISTRY_RELATIVE
    proxy = data_root / PROXY_RELATIVE
    labels_path = data_root / LABEL_SQLITE_RELATIVE
    roles = load_issue_roles(candidate, registry)
    panel = load_proxy_panel(proxy, roles)
    panel = panel[
        panel["snapshot_kind"].eq(HORIZON)
        & panel["issue_year"].isin((*WARMUP_YEARS, *PANEL_YEARS))
    ].copy()
    panel["issue_year"] = pd.to_numeric(panel["issue_year"], errors="raise").astype(int)
    development_issues = set(
        panel.loc[panel["issue_year"].le(max(OOF_YEARS)), "issue_code"].astype(str)
    )
    labels = load_development_labels(labels_path, development_issues)
    development = attach_native_labels(panel, labels)
    source_hashes = {
        "candidate_sqlite_sha256": sha256_file(candidate),
        "proxy_manifest_sha256": sha256_file(proxy / "MANIFEST.json"),
        "consumed_issue_roles_sha256": stable_frame_sha(roles),
        "consumed_development_labels_sha256": stable_frame_sha(labels),
        "accepted_238_probability_sha256": sha256_file(data_root / ACCEPTED_238_RELATIVE),
    }
    return panel, development, source_hashes


def _model_receipt(model: Pipeline, *, target_years: list[int], train_year_max: int) -> dict[str, Any]:
    transformer = model.named_steps["features"]
    estimator = model.named_steps["model"]
    return {
        "target_years": target_years,
        "train_year_max": train_year_max,
        "classes": [str(value) for value in estimator.classes_],
        "feature_names": [str(value) for value in transformer.get_feature_names_out()],
        "coef": estimator.coef_.tolist(),
        "intercept": estimator.intercept_.tolist(),
        "n_iter": estimator.n_iter_.tolist(),
    }


def _predict_years(
    panel: pd.DataFrame,
    development: pd.DataFrame,
) -> tuple[pd.DataFrame, list[dict[str, Any]]]:
    predictions: list[pd.DataFrame] = []
    receipts: list[dict[str, Any]] = []
    target_groups = [([year], year - 1) for year in OOF_YEARS]
    target_groups.append((list(TRANSFER_YEARS), max(OOF_YEARS)))
    for target_years, train_year_max in target_groups:
        train = development[
            development["issue_year"].le(train_year_max)
            & development["target_outcome"].notna()
            & development["native_line_supported"].eq(True)
        ].copy()
        if int(train["issue_year"].min()) > min(WARMUP_YEARS):
            raise ContractError("warm-up years escaped the training partition")
        if int(train["issue_year"].max()) != train_year_max:
            raise ContractError(f"training partition does not end in {train_year_max}")
        if set(train["target_outcome"].astype(str)) != set(OUTCOMES):
            raise ContractError("training partition lacks all outcome classes")
        experimental = _model()
        control = _control_model()
        experimental.fit(train, train["target_outcome"].astype(str))
        control.fit(train, train["target_outcome"].astype(str))
        target = panel[
            panel["issue_year"].isin(target_years)
            & panel["native_line_supported"].eq(True)
        ].copy()
        if target.empty:
            raise ContractError(f"no supported target rows for {target_years}")
        q_candidate = _ordered_probability(experimental, target)
        q_line = _ordered_probability(control, target)
        zero_line = target["native_handicap_line"].eq(0).to_numpy()
        for position, outcome in enumerate(OUTCOMES):
            target[f"q_candidate_{outcome}"] = np.where(
                zero_line,
                target[f"q_eu_{outcome}"].to_numpy(float),
                q_candidate[:, position],
            )
            target[f"q_line_{outcome}"] = q_line[:, position]
        target["prediction_role"] = np.where(
            target["issue_year"].isin(OOF_YEARS),
            "STRICTLY_PRIOR_EXPANDING_OOF",
            "FROZEN_THROUGH_2021_TRANSFER",
        )
        target["train_year_max"] = train_year_max
        predictions.append(target)
        receipt = _model_receipt(
            experimental,
            target_years=target_years,
            train_year_max=train_year_max,
        )
        receipt["control"] = _model_receipt(
            control,
            target_years=target_years,
            train_year_max=train_year_max,
        )
        receipts.append(receipt)
    predicted = pd.concat(predictions, ignore_index=True)
    if set(predicted["issue_year"].unique()) != set(PANEL_YEARS):
        raise ContractError("prediction years are incomplete")
    if not (predicted["train_year_max"] < predicted["issue_year"]).all():
        raise ContractError("target year leaked into model training")
    return predicted, receipts


def _fixture_features(predicted: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    for row in predicted.itertuples(index=False):
        q = {code: float(getattr(row, f"q_candidate_{code}")) for code in OUTCOMES}
        raw = {code: float(getattr(row, f"q_eu_{code}")) for code in OUTCOMES}
        line = {code: float(getattr(row, f"q_line_{code}")) for code in OUTCOMES}
        ranked = sorted(OUTCOMES, key=lambda code: (-q[code], OUTCOME_ORDER[code]))
        top1, top2, omitted = ranked
        retained = q[top1] + q[top2]
        divergence = {code: q[code] - line[code] for code in OUTCOMES}
        record: dict[str, Any] = {
            "issue": str(row.issue_code),
            "issue_year": int(row.issue_year),
            "issue_anchor_ts": pd.Timestamp(row.issue_anchor_ts),
            "match_idx": int(row.match_idx),
            "prediction_role": str(row.prediction_role),
            "train_year_max": int(row.train_year_max),
            "baseline_support": f"{top1}{top2}",
            "omitted_outcome": omitted,
            "retained_mass": retained,
            "p_min": q[omitted],
            "top1_probability": q[top1],
            "top2_probability": q[top2],
            "top1_top2_gap": q[top1] - q[top2],
            "top2_top3_gap": q[top2] - q[omitted],
            "probability_entropy": -sum(value * math.log(value) for value in q.values()),
            "probability_hhi": sum(value * value for value in q.values()),
            "native_handicap_line": float(row.native_handicap_line),
            "abs_native_handicap_line": abs(float(row.native_handicap_line)),
            "n_available_books": int(row.n_available_books),
            "causal_grade": str(row.causal_grade),
            "divergence_l1": sum(abs(value) for value in divergence.values()),
            "divergence_max_abs": max(abs(value) for value in divergence.values()),
            "divergence_omitted": divergence[omitted],
            "divergence_top2_mean_abs": (
                abs(divergence[top1]) + abs(divergence[top2])
            ) / 2,
        }
        for code in OUTCOMES:
            record[f"q_candidate_{code}"] = q[code]
            record[f"q_raw_eu_{code}"] = raw[code]
            record[f"q_line_{code}"] = line[code]
            record[f"divergence_{code}"] = divergence[code]
        rows.append(record)
    features = pd.DataFrame(rows)
    if features.duplicated(list(FEATURE_KEY)).any():
        raise ContractError("fixture features are not unique")
    q_columns = [f"q_candidate_{code}" for code in OUTCOMES]
    values = features[q_columns].to_numpy(float)
    if not np.isfinite(values).all() or (values <= 0).any():
        raise ContractError("fixture probability surface is invalid")
    if not np.allclose(values.sum(axis=1), 1.0, rtol=0, atol=PROBABILITY_ATOL):
        raise ContractError("fixture probability triplets are not normalized")
    return features


def _load_label_frame(
    data_root: Path,
    features: pd.DataFrame,
    development: pd.DataFrame,
) -> pd.DataFrame:
    development_labels = development[
        development["issue_year"].isin(OOF_YEARS)
        & development["target_outcome"].notna()
    ][["issue_code", "match_idx", "target_outcome"]].drop_duplicates()
    development_labels = development_labels.rename(
        columns={"issue_code": "issue", "target_outcome": "result_code"}
    )
    transfer_issues = sorted(
        features.loc[features["issue_year"].isin(TRANSFER_YEARS), "issue"].unique()
    )
    placeholders = ",".join("?" for _ in transfer_issues)
    with _connect_read_only(data_root / LABEL_SQLITE_RELATIVE) as connection:
        transfer = pd.read_sql_query(
            f"""
            SELECT CAST(issue AS TEXT) AS issue, match_idx,
                   CAST(result_code AS TEXT) AS result_code,
                   CAST(has_trusted_settlement AS INTEGER) AS trusted
            FROM match_features
            WHERE CAST(issue AS TEXT) IN ({placeholders})
            ORDER BY issue, match_idx
            """,
            connection,
            params=transfer_issues,
        )
    transfer = transfer.drop_duplicates(list(LABEL_KEY), keep="first")
    transfer = transfer[
        transfer["trusted"].eq(1) & transfer["result_code"].isin(OUTCOMES)
    ][["issue", "match_idx", "result_code"]]
    labels = pd.concat([development_labels, transfer], ignore_index=True)
    labels["issue"] = labels["issue"].astype(str)
    labels["result_code"] = labels["result_code"].astype(str)
    labels = features[["issue", "issue_year", "match_idx", "baseline_support"]].merge(
        labels,
        on=["issue", "match_idx"],
        how="left",
        validate="one_to_one",
    )
    labels["label_available"] = labels["result_code"].isin(OUTCOMES)
    labels["top2_hit"] = pd.array(
        [
            (result in support) if available else pd.NA
            for result, support, available in zip(
                labels["result_code"],
                labels["baseline_support"],
                labels["label_available"],
                strict=True,
            )
        ],
        dtype="boolean",
    )
    return labels.drop(columns="baseline_support").sort_values(
        ["issue_year", "issue", "match_idx"], kind="stable"
    ).reset_index(drop=True)


def _mass_bin(values: pd.Series) -> pd.Series:
    return pd.cut(
        values,
        bins=list(MASS_BIN_EDGES),
        include_lowest=True,
        right=True,
        labels=False,
    ).astype("Int64")


def _attach_prior_calibration(features: pd.DataFrame, labels: pd.DataFrame) -> pd.DataFrame:
    merged = features.merge(
        labels[["issue", "match_idx", "top2_hit", "label_available"]],
        on=["issue", "match_idx"],
        how="left",
        validate="one_to_one",
    )
    merged["mass_bin"] = _mass_bin(merged["retained_mass"])
    output: list[pd.DataFrame] = []
    history = merged.iloc[0:0].copy()
    for year in PANEL_YEARS:
        current = merged[merged["issue_year"].eq(year)].copy()
        available = history[history["label_available"].eq(True)].copy()
        if available.empty:
            current["prior_global_count"] = 0
            current["prior_global_hit_rate"] = current["retained_mass"]
            current["prior_global_residual"] = 0.0
            for prefix in ("mass_bin", "line", "omitted"):
                current[f"prior_{prefix}_count"] = 0
                current[f"prior_{prefix}_hit_rate"] = current["retained_mass"]
                current[f"prior_{prefix}_residual"] = 0.0
        else:
            available["top2_hit_float"] = available["top2_hit"].astype(float)
            global_count = int(len(available))
            global_hits = float(available["top2_hit_float"].sum())
            global_expected = float(available["retained_mass"].sum())
            current["prior_global_count"] = global_count
            current["prior_global_hit_rate"] = (
                global_hits + CALIBRATION_PRIOR_STRENGTH * current["retained_mass"]
            ) / (global_count + CALIBRATION_PRIOR_STRENGTH)
            current["prior_global_residual"] = (
                global_hits - global_expected
            ) / global_count

            group_specs = {
                "mass_bin": ["mass_bin"],
                "line": ["native_handicap_line"],
                "omitted": ["omitted_outcome"],
            }
            for prefix, keys in group_specs.items():
                stats = (
                    available.groupby(keys, observed=True, dropna=False)
                    .agg(
                        group_count=("top2_hit_float", "size"),
                        group_hits=("top2_hit_float", "sum"),
                        group_expected=("retained_mass", "sum"),
                    )
                    .reset_index()
                )
                current = current.merge(stats, on=keys, how="left", validate="many_to_one")
                count = current["group_count"].fillna(0).astype(int)
                hits = current["group_hits"].fillna(0.0)
                expected = current["group_expected"].fillna(0.0)
                current[f"prior_{prefix}_count"] = count
                current[f"prior_{prefix}_hit_rate"] = (
                    hits + CALIBRATION_PRIOR_STRENGTH * current["retained_mass"]
                ) / (count + CALIBRATION_PRIOR_STRENGTH)
                current[f"prior_{prefix}_residual"] = np.where(
                    count.gt(0), (hits - expected) / count, 0.0
                )
                current = current.drop(
                    columns=["group_count", "group_hits", "group_expected"]
                )
        output.append(current)
        history = pd.concat([history, merged[merged["issue_year"].eq(year)]], ignore_index=True)
    result = pd.concat(output, ignore_index=True)
    return result.drop(columns=["top2_hit", "label_available"])


def _attach_issue_relative(features: pd.DataFrame) -> pd.DataFrame:
    group = features.groupby(["issue_year", "issue"], observed=True, sort=False)
    features = features.copy()
    features["issue_fixture_count"] = group["match_idx"].transform("size")
    features["retained_mass_rank"] = group["retained_mass"].rank(
        method="first", ascending=False
    ).astype(int)
    features["retained_mass_percentile"] = group["retained_mass"].rank(
        method="average", pct=True, ascending=True
    )
    features["divergence_abs_percentile"] = group["divergence_l1"].rank(
        method="average", pct=True, ascending=True
    )
    features["books_percentile"] = group["n_available_books"].rank(
        method="average", pct=True, ascending=True
    )
    features["issue_retained_mean"] = group["retained_mass"].transform("mean")
    features["issue_retained_std"] = group["retained_mass"].transform("std").fillna(0)
    features["issue_retained_min"] = group["retained_mass"].transform("min")
    features["issue_retained_max"] = group["retained_mass"].transform("max")
    for n in (3, 4, 5):
        cutoff = group["retained_mass"].transform(
            lambda values, n=n: (
                float(values.nlargest(n).iloc[-1]) if len(values) >= n else np.nan
            )
        )
        features[f"retained_gap_to_n{n}_cutoff"] = features["retained_mass"] - cutoff
    return features.sort_values(
        ["issue_year", "issue_anchor_ts", "issue", "match_idx"], kind="stable"
    ).reset_index(drop=True)


def _parity_with_accepted(data_root: Path, features: pd.DataFrame) -> pd.DataFrame:
    accepted = pq.read_table(
        data_root / ACCEPTED_238_RELATIVE,
        filters=[("snapshot_kind", "=", HORIZON), ("issue_year", "in", list(TRANSFER_YEARS))],
        columns=[
            "issue_code",
            "match_idx",
            "outcome_code",
            "q_eu_bjline",
            "q_eu_bjline_candidate_diagnostic",
            "native_handicap_line",
            "native_line_supported",
        ],
    ).to_pandas()
    accepted = accepted[accepted["native_line_supported"].eq(True)].copy()
    candidate = features.melt(
        id_vars=["issue", "match_idx"],
        value_vars=[f"q_candidate_{code}" for code in OUTCOMES],
        var_name="candidate_column",
        value_name="q_candidate",
    )
    candidate["outcome_code"] = candidate["candidate_column"].str.rsplit("_", n=1).str[-1]
    candidate = candidate.drop(columns="candidate_column")
    merged = candidate.merge(
        accepted,
        left_on=["issue", "match_idx", "outcome_code"],
        right_on=["issue_code", "match_idx", "outcome_code"],
        how="inner",
        validate="one_to_one",
    )
    candidate_delta = (
        merged["q_candidate"] - merged["q_eu_bjline_candidate_diagnostic"]
    ).abs()
    accepted_delta = (merged["q_candidate"] - merged["q_eu_bjline"]).abs()
    nonzero = merged["native_handicap_line"].ne(0)
    return pd.DataFrame(
        [
            {
                "years": "2022-2024",
                "compared_cells": int(len(merged)),
                "max_abs_delta_vs_candidate_diagnostic": float(candidate_delta.max()),
                "exact_cells_vs_candidate_diagnostic": int(candidate_delta.eq(0).sum()),
                "nonzero_cells": int(nonzero.sum()),
                "nonzero_max_abs_delta_vs_candidate_diagnostic": float(
                    candidate_delta.loc[nonzero].max()
                ),
                "nonzero_exact_cells_vs_candidate_diagnostic": int(
                    candidate_delta.loc[nonzero].eq(0).sum()
                ),
                "max_abs_delta_vs_accepted_q_eu_bjline": float(accepted_delta.max()),
                "exact_cells_vs_accepted_q_eu_bjline": int(accepted_delta.eq(0).sum()),
                "interpretation": (
                    "same frozen architecture refit through 2021; nonzero-line candidate "
                    "diagnostic parity and full accepted-surface numeric parity are reported, "
                    "without inheriting the outcome-confirmed mapping_accepted gate"
                ),
            }
        ]
    )


def _coverage(features: pd.DataFrame, labels: pd.DataFrame) -> pd.DataFrame:
    merged = features.merge(
        labels[["issue", "match_idx", "label_available"]],
        on=["issue", "match_idx"],
        how="left",
        validate="one_to_one",
    )
    return (
        merged.groupby(["issue_year", "prediction_role"], observed=True, sort=True)
        .agg(
            issues=("issue", "nunique"),
            fixtures=("match_idx", "size"),
            median_fixtures_per_issue=("issue_fixture_count", "median"),
            label_available=("label_available", "sum"),
            mean_books=("n_available_books", "mean"),
            mean_retained_mass=("retained_mass", "mean"),
        )
        .reset_index()
    )


def _field_dictionary(features: pd.DataFrame, labels: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict[str, str]] = []
    for artifact, frame in (("features", features), ("labels", labels)):
        for column in frame.columns:
            rows.append(
                {
                    "artifact": artifact,
                    "field": column,
                    "dtype": str(frame[column].dtype),
                    "availability": (
                        "POST_OUTCOME_SEPARATE" if artifact == "labels" else "PRE_OUTCOME"
                    ),
                }
            )
    return pd.DataFrame(rows)


def _implementation_hashes(repo_root: Path) -> dict[str, str]:
    paths = [
        repo_root / "src/low_n_selector_data/__init__.py",
        repo_root / "src/low_n_selector_data/contract.py",
        repo_root / "src/low_n_selector_data/pipeline.py",
        repo_root / "scripts/run_low_n_selector_data.py",
        repo_root / "scripts/verify_low_n_selector_data.py",
        repo_root / "scripts/build_low_n_selector_data_notebook.py",
    ]
    return {str(path.relative_to(repo_root)): sha256_file(path) for path in paths}


def _scientific_frames(repo_root: Path, data_root: Path) -> dict[str, Any]:
    panel, development, source_hashes = _input_panel(data_root)
    predicted, model_receipts = _predict_years(panel, development)
    features = _fixture_features(predicted)
    labels = _load_label_frame(data_root, features, development)
    features = _attach_prior_calibration(features, labels)
    features = _attach_issue_relative(features)
    coverage = _coverage(features, labels)
    parity = _parity_with_accepted(data_root, features)
    dictionary = _field_dictionary(features, labels)
    freeze_receipt = {
        "contract": CONTRACT_ID,
        "primary_horizon": HORIZON,
        "warmup_years": list(WARMUP_YEARS),
        "oof_years": list(OOF_YEARS),
        "selector_development_years": list(SELECTOR_DEVELOPMENT_YEARS),
        "transfer_years": list(TRANSFER_YEARS),
        "transfer_role": "EXPOSED_HISTORICAL_TRANSFER_ONLY",
        "model_selection_outcomes_allowed_through": 2021,
        "feature_frame_sha256": stable_frame_sha(features),
        "feature_rows": int(len(features)),
        "label_frame_sha256": stable_frame_sha(labels),
        "label_rows": int(len(labels)),
        "model_receipts": model_receipts,
    }
    return {
        "features": features,
        "labels": labels,
        "coverage": coverage,
        "parity": parity,
        "dictionary": dictionary,
        "source_receipt": {
            "contract": CONTRACT_ID,
            "data_root_disclosed_at_build": str(data_root),
            **source_hashes,
        },
        "freeze_receipt": freeze_receipt,
        "implementation_hashes": _implementation_hashes(repo_root),
    }


def build_package(
    repo_root: Path,
    target: Path,
    explicit_data_root: Path | None = None,
    *,
    force: bool = False,
) -> dict[str, Any]:
    repo_root = Path(repo_root).resolve()
    data_root = locate_data_root(repo_root, explicit_data_root)
    frames = _scientific_frames(repo_root, data_root)

    def populate(staging: Path) -> None:
        atomic_write_parquet(frames["features"], staging / "features" / "selector_features.parquet")
        atomic_write_parquet(frames["labels"], staging / "labels" / "selector_labels.parquet")
        atomic_write_csv(frames["coverage"], staging / "analysis" / "coverage.csv")
        atomic_write_csv(frames["parity"], staging / "analysis" / "accepted_surface_parity.csv")
        atomic_write_csv(frames["dictionary"], staging / "analysis" / "field_dictionary.csv")
        atomic_write_json(staging / "SOURCE_RECEIPT.json", frames["source_receipt"])
        atomic_write_json(staging / "FREEZE_RECEIPT.json", frames["freeze_receipt"])
        files = {
            str(path.relative_to(staging)): sha256_file(path)
            for path in sorted(staging.rglob("*"))
            if path.is_file()
        }
        atomic_write_json(
            staging / "MANIFEST.json",
            {
                "contract": CONTRACT_ID,
                "implementation_files": frames["implementation_hashes"],
                "files": files,
            },
        )

    atomic_publish_directory(Path(target), populate, force=force)
    return frames["freeze_receipt"]


def _read_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def verify_package(repo_root: Path, target: Path, explicit_data_root: Path | None = None) -> dict[str, bool]:
    repo_root = Path(repo_root).resolve()
    target = Path(target).resolve()
    data_root = locate_data_root(repo_root, explicit_data_root)
    manifest = _read_json(target / "MANIFEST.json")
    expected_files = manifest.get("files")
    if not isinstance(expected_files, dict) or not expected_files:
        raise AssertionError("manifest file table is empty")
    manifest_hashes = all(
        (target / relative).is_file()
        and sha256_file(target / relative) == digest
        for relative, digest in expected_files.items()
    )
    if not manifest_hashes:
        raise AssertionError("manifest file hashes do not match")
    implementation = manifest.get("implementation_files")
    expected_implementation = _implementation_hashes(repo_root)
    if implementation != expected_implementation:
        raise AssertionError("implementation hashes do not match current code")
    source_receipt = _read_json(target / "SOURCE_RECEIPT.json")
    current = _scientific_frames(repo_root, data_root)
    source_bound = all(
        source_receipt.get(key) == value
        for key, value in current["source_receipt"].items()
        if key != "data_root_disclosed_at_build"
    )
    if not source_bound:
        raise AssertionError("canonical source hashes changed")
    features = pq.read_table(target / "features/selector_features.parquet").to_pandas()
    labels = pq.read_table(target / "labels/selector_labels.parquet").to_pandas()
    freeze = _read_json(target / "FREEZE_RECEIPT.json")
    semantic_hashes = (
        freeze.get("feature_frame_sha256") == stable_frame_sha(features)
        and freeze.get("label_frame_sha256") == stable_frame_sha(labels)
        and stable_frame_sha(features) == stable_frame_sha(current["features"])
        and stable_frame_sha(labels) == stable_frame_sha(current["labels"])
    )
    if not semantic_hashes:
        raise AssertionError("scientific frames do not replay from sources")
    temporal = (
        set(features["issue_year"].unique()) == set(PANEL_YEARS)
        and (features["train_year_max"] < features["issue_year"]).all()
        and set(features.loc[features["issue_year"].isin(TRANSFER_YEARS), "train_year_max"]) == {2021}
    )
    if not temporal:
        raise AssertionError("temporal contract failed")
    label_separation = not any(
        column in features.columns
        for column in ("result_code", "top2_hit", "winning_sp", "settlement_sp")
    )
    if not label_separation:
        raise AssertionError("outcome labels leaked into feature artifact")
    return {
        "manifest_hashes": manifest_hashes,
        "implementation_hashes": True,
        "source_bound_replay": source_bound,
        "semantic_frame_replay": semantic_hashes,
        "strict_temporal_lineage": temporal,
        "label_separation": label_separation,
        "probability_simplex": True,
    }
