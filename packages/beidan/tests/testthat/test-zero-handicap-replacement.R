test_that("zero handicap replacement is aligned and preserves other fixtures", {
 p <- tibble::tibble(fixture_id=rep(c("001","002"),each=3),outcome=rep(c("W","D","L"),2),probability=c(.5,.3,.2,.2,.3,.5))
 e <- p;e$probability <- c(.4,.35,.25,.3,.3,.4)
 f <- tibble::tibble(fixture_id=c("001","002"),handicap=c(0,-1))
 x <- ReplaceZeroHandicapProbability(p,e[6:1,],f)
 expect_equal(x$probability,c(.4,.35,.25,.2,.3,.5))
 expect_identical(x$fixture_id,p$fixture_id)
 expect_s3_class(x,"tbl_df")
 f$handicap <- c(1,-1);expect_identical(ReplaceZeroHandicapProbability(p,e,f),p)
 f$handicap <- c(0,0);expect_identical(ReplaceZeroHandicapProbability(p,e,f),e)
 expect_error(ReplaceZeroHandicapProbability(p,e[-1,],f))
 expect_error(ReplaceZeroHandicapProbability(p,e,f[-1,]))
 expect_error(ReplaceZeroHandicapProbability(p,e,dplyr::bind_rows(f,f[1,])))
 f$handicap[1] <- NA_real_;expect_error(ReplaceZeroHandicapProbability(p,e,f))
 expect_error(ReplaceZeroHandicapProbability(p[0,],e[0,],f[0,]))
})
