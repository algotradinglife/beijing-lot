# Package tests for the role candidate-pool stage (parlay_construct_role_groups, issue
# #537) and its internal helpers, exercised through observable plan behavior. The
# root's independent acceptance test is separate and not edited here.

role_plan_cutoff <- function(issue_id = "26098") {
  list(issue_id = issue_id,
       cutoff_utc = as.POSIXct("2026-09-26 11:52:04", tz = "UTC"))
}

role_plan_settings <- function(n_legs, issue_budget_cny = 1024, unit_cny = 2) {
  settings <- parlay_settings()
  settings$n_legs <- as.integer(n_legs)
  settings$issue_budget_cny <- issue_budget_cny
  settings$unit_cny <- unit_cny
  settings
}

# A pool of `n` fixtures whose probabilities are all distinct but small enough that
# role scores do not tie by accident.
role_plan_probabilities <- function(n) {
  base <- seq(0.60, 0.05, length.out = n)
  rows <- lapply(seq_len(n), function(i) {
    p <- c(base[i], (1 - base[i]) * 0.7, (1 - base[i]) * 0.3)
    tibble::tibble(fixture_id = sprintf("26098:%02d", i),
                   outcome = c("W", "D", "L"), probability = p)
  })
  dplyr::bind_rows(rows)
}

test_that("the pool is generated by bounded deterministic rank-start offsets", {
  probabilities <- role_plan_probabilities(28)
  cutoff <- role_plan_cutoff()
  settings <- role_plan_settings(7L)
  pool <- parlay_construct_role_groups(
    parlay_role_scores(probabilities, cutoff), cutoff, settings,
    pattern = c(3L, 3L, 3L, 3L, 2L, 2L, 2L), n_candidates = 4L,
    probabilities = probabilities)
  # Four generated candidates, all complete, each with seven distinct fixtures.
  expect_identical(nrow(pool$groups), 4L)
  expect_true(all(pool$groups$complete))
  expect_identical(dplyr::n_distinct(pool$groups$group_id), 4L)
  # GLOBAL snake rounds order the turns 1..4 then 4..1 across the role transitions.
  chosen <- pool$trace[pool$trace$action == "selected", , drop = FALSE]
  expect_identical(chosen$round, rep(1:7, each = 4))
  expect_identical(chosen$group_slot, c(1:4, 4:1, 1:4, 4:1, 1:4, 4:1, 1:4))
  # No fixture repeats inside one group.
  per_group <- split(as.character(pool$role_legs$fixture_id),
                     as.character(pool$role_legs$group_slot))
  expect_true(all(vapply(per_group, function(x) !anyDuplicated(x), logical(1))))
  # The rank-start offset makes the pool diverse: the four groups do NOT all take the
  # same highest-ranked fixture in round 1.
  top <- pool$role_legs$fixture_id[pool$role_legs$round == 1L]
  expect_identical(dplyr::n_distinct(top), 4L)
})

test_that("changing the budget or group depth never changes the candidate pool", {
  probabilities <- role_plan_probabilities(28)
  cutoff <- role_plan_cutoff()
  base <- parlay_construct_role_groups(
    parlay_role_scores(probabilities, cutoff), cutoff, role_plan_settings(7L, 1024),
    pattern = c(3L, 2L, 2L, 2L, 2L, 2L, 1L), n_candidates = 4L,
    probabilities = probabilities)
  tiny <- parlay_construct_role_groups(
    parlay_role_scores(probabilities, cutoff), cutoff, role_plan_settings(7L, 1),
    pattern = c(3L, 2L, 2L, 2L, 2L, 2L, 1L), n_candidates = 4L,
    probabilities = probabilities)
  huge <- parlay_construct_role_groups(
    parlay_role_scores(probabilities, cutoff), cutoff, role_plan_settings(7L, 99999),
    pattern = c(3L, 2L, 2L, 2L, 2L, 2L, 1L), n_candidates = 4L,
    probabilities = probabilities)
  expect_identical(base$role_legs, tiny$role_legs)
  expect_identical(base$groups, tiny$groups)
  expect_identical(base$role_legs, huge$role_legs)
  expect_identical(base$groups, huge$groups)
})

test_that("between-candidate reuse and overlap are allowed at generation", {
  probabilities <- role_plan_probabilities(4)
  cutoff <- role_plan_cutoff()
  # Four fixtures, two-leg groups and a large n_candidates: there are only six
  # distinct fixture pairs, and the offset scan will reuse fixtures across groups.
  pool <- parlay_construct_role_groups(
    parlay_role_scores(probabilities, cutoff), cutoff, role_plan_settings(2L),
    pattern = c(2L, 1L), n_candidates = 4L, probabilities = probabilities)
  sets <- split(as.character(pool$role_legs$fixture_id),
                as.character(pool$role_legs$group_slot))
  # A fixture appearing in more than one group proves reuse is admitted here; the
  # final selection stage is where the caps are applied.
  expect_gt(max(table(unlist(sets))), 1L)
  # Identical fixture/role/mask packages are de-duplicated; a fixture set can
  # legitimately have two different role assignments.
  blocks <- split(pool$role_legs, pool$role_legs$group_slot)
  keys <- vapply(blocks, function(x) {
    x <- x[order(x$fixture_id), ]
    paste(x$fixture_id, x$role, vapply(x$allowed_outcomes, paste, character(1), collapse = "/"), collapse = "|")
  }, character(1))
  expect_identical(anyDuplicated(keys), 0L)
})

test_that("n_candidates is a maximum and shortages are explicit", {
  cutoff <- role_plan_cutoff()
  # Two fixtures under a two-leg pattern: only ONE distinct pair exists, so a
  # four-candidate request is de-duplicated down to a single package and every other
  # candidate's slots are recorded as shortages rather than fabricated.
  probabilities <- role_plan_probabilities(2)
  pool <- parlay_construct_role_groups(
    parlay_role_scores(probabilities, cutoff), cutoff, role_plan_settings(2L),
    pattern = c(3L, 3L), n_candidates = 4L, probabilities = probabilities)
  expect_lte(nrow(pool$groups[pool$groups$complete, , drop = FALSE]), 1L)
  expect_gt(nrow(pool$shortages), 0L)
  expect_true(all(c("group_slot", "group_id", "round", "turn", "role", "reason") %in%
                    names(pool$shortages)))
  expect_true(all(pool$role_legs$fixture_id %in% probabilities$fixture_id))
})

test_that("an empty admitted pool returns a typed-empty candidate pool", {
  cutoff <- role_plan_cutoff()
  empty <- match_typed_empty("probabilities")
  pool <- parlay_construct_role_groups(parlay_role_scores(empty, cutoff), cutoff,
                                       role_plan_settings(2L), pattern = c(2L, 1L),
                                       n_candidates = 3L, probabilities = empty)
  expect_identical(nrow(pool$groups), 0L)
  expect_identical(nrow(pool$role_legs), 0L)
  expect_identical(nrow(pool$shortages), 0L)
  expect_identical(names(pool$groups), c("group_slot", "group_id", "complete"))
  # The empty pool still carries the cutoff binding so it cannot be retimed.
  expect_identical(pool$cutoff_hash, rlang::hash(list(as.character(cutoff$issue_id), as.numeric(cutoff$cutoff_utc))))
})

test_that("parlay_construct_role_groups validates its explicit inputs", {
  probabilities <- role_plan_probabilities(6)
  cutoff <- role_plan_cutoff()
  settings <- role_plan_settings(2L)
  scores <- parlay_role_scores(probabilities, cutoff)
  # probabilities is required: ranks must be re-derivable, not trusted from attrs.
  expect_error(parlay_construct_role_groups(scores, cutoff, settings, c(2L, 1L), 4L),
               "probabilities")
  # Cutoff mismatch between settings and the decision is refused.
  stray <- settings
  stray$cutoff <- list(issue_id = "99999", cutoff_utc = cutoff$cutoff_utc)
  expect_error(parlay_construct_role_groups(scores, cutoff, stray, c(2L, 1L), 4L,
                                            probabilities = probabilities), "cutoff")
  # A pattern of the wrong width and out-of-range roles are refused.
  expect_error(parlay_construct_role_groups(scores, cutoff, settings, c(1L, 2L, 3L),
                                            4L, probabilities = probabilities),
               "pattern")
  expect_error(parlay_construct_role_groups(scores, cutoff, settings, c(0L, 1L), 4L,
                                            probabilities = probabilities), "pattern")
  # n_candidates must be a positive whole number.
  expect_error(parlay_construct_role_groups(scores, cutoff, settings, c(2L, 1L), 0L,
                                            probabilities = probabilities),
               "n_candidates")
  expect_error(parlay_construct_role_groups(scores, cutoff, settings, c(2L, 1L), 1.5,
                                            probabilities = probabilities),
               "n_candidates")
})

test_that("a tampered score or rank is refused, not obeyed", {
  probabilities <- role_plan_probabilities(6)
  cutoff <- role_plan_cutoff()
  settings <- role_plan_settings(2L)
  scores <- parlay_role_scores(probabilities, cutoff)
  tampered <- scores
  tampered$score[1] <- tampered$score[1] + 10
  expect_error(parlay_construct_role_groups(tampered, cutoff, settings, c(2L, 1L), 4L,
                                            probabilities = probabilities), "disagree")
  tampered_rank <- scores
  tampered_rank$rank[1] <- 99L
  expect_error(parlay_construct_role_groups(tampered_rank, cutoff, settings,
                                            c(2L, 1L), 4L,
                                            probabilities = probabilities), "disagree")
})

test_that("the pool carries the frozen context, hash and sorted pattern", {
  probabilities <- role_plan_probabilities(6)
  cutoff <- role_plan_cutoff()
  settings <- role_plan_settings(2L)
  scores <- parlay_role_scores(probabilities, cutoff)
  pool <- parlay_construct_role_groups(scores, cutoff, settings, pattern = c(1L, 2L),
                                       n_candidates = 2L, probabilities = probabilities)
  expect_identical(pool$cutoff, cutoff)
  expect_identical(pool$probability_hash, rlang::hash(probabilities))
  expect_identical(pool$pattern, c(2L, 1L))
  expect_identical(pool$settings, settings)
  # The cutoff identity is frozen as a hash, computed by the one shared helper.
  expect_identical(pool$cutoff_hash, rlang::hash(list(as.character(cutoff$issue_id), as.numeric(cutoff$cutoff_utc))))
  retimed <- cutoff
  retimed$cutoff_utc <- cutoff$cutoff_utc + 60
  expect_false(identical(pool$cutoff_hash,
                         rlang::hash(list(as.character(retimed$issue_id), as.numeric(retimed$cutoff_utc)))))
  expect_true(all(c("role_legs", "groups", "trace", "shortages", "cutoff", "settings",
                    "probability_hash", "prematch_sp", "prematch_sp_hash",
                    "cutoff_hash", "scores") %in% names(pool)))
  # The default SP state is the explicit typed-empty historical "missing" table.
  expect_identical(pool$prematch_sp, match_typed_empty("prematch_sp"))
  expect_identical(pool$prematch_sp_hash, rlang::hash(pool$prematch_sp))
})

test_that("the pool freezes a strictly pre-cutoff SP table and rejects leakage", {
  probabilities <- role_plan_probabilities(4)
  cutoff <- role_plan_cutoff()
  settings <- role_plan_settings(2L)
  scores <- parlay_role_scores(probabilities, cutoff)
  sp <- dplyr::mutate(dplyr::select(probabilities, fixture_id, outcome),
                      quote_at = cutoff$cutoff_utc - 60, sp_raw = 12,
                      source_url = "test")
  pool <- parlay_construct_role_groups(scores, cutoff, settings, c(2L, 1L), 2L,
                                       probabilities = probabilities, prematch_sp = sp)
  expect_identical(pool$prematch_sp, sp)
  expect_identical(pool$prematch_sp_hash, rlang::hash(sp))
  # A quote exactly at the cutoff is not available to the decision.
  at_cutoff <- sp
  at_cutoff$quote_at <- cutoff$cutoff_utc
  expect_error(parlay_construct_role_groups(scores, cutoff, settings, c(2L, 1L), 2L,
    probabilities = probabilities, prematch_sp = at_cutoff), "strictly")
  # Neither is a future quote.
  future <- sp
  future$quote_at <- cutoff$cutoff_utc + 1
  expect_error(parlay_construct_role_groups(scores, cutoff, settings, c(2L, 1L), 2L,
    probabilities = probabilities, prematch_sp = future), "strictly")
})

test_that("the internal feasibility arithmetic matches the observable pool", {
  # Generation only forbids a duplicate inside the group under construction.
  expect_true(beidan:::.parlay_role_feasible("A", character(0))$feasible)
  duplicate <- beidan:::.parlay_role_feasible("A", "A")
  expect_false(duplicate$feasible)
  expect_identical(duplicate$reason, "duplicate_fixture_in_group")
})

test_that("type validation helpers refuse their documented bad inputs", {
  probabilities <- role_plan_probabilities(6)
  cutoff <- role_plan_cutoff()
  scores <- parlay_role_scores(probabilities, cutoff)
  expect_error(beidan:::.parlay_role_validate_scores("not a table", probabilities),
               "role score tibble")
  missing_column <- scores[, setdiff(names(scores), "rank")]
  expect_error(beidan:::.parlay_role_validate_scores(missing_column, probabilities),
               "rank")
  expect_error(beidan:::.parlay_role_validate_pattern(c(1.5, 2), 2L), "whole numbers")
  expect_error(beidan:::.parlay_role_validate_n_candidates(0L), "n_candidates")
})
