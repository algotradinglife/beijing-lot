test_that("recent venue wrapper preserves numeric and typed contracts", {
  root <- Sys.getenv("FM_NATIVE_TEST_ROOT")
  stopifnot(nzchar(root))
  source(file.path(root,"packages/beidan/R/recent_venue_goals.R"),local=TRUE)
  reticulate::use_python(file.path(root,".venv/bin/python"),required=TRUE)
  reticulate::import("sys",convert=FALSE)$path$insert(0L,file.path(root,"packages/beidan/inst/python"))
  shared <- reticulate::import("beidan_backend.temporal_learning",convert=FALSE)
  input_path <- file.path(root,"results/fm-native-65-20261011/input.json")
  x <- jsonlite::fromJSON(input_path,simplifyVector=FALSE)
  h <- dplyr::bind_rows(x$rows)
  c <- shared$Cutoff$decision_epoch("26101",x$cutoff)
  p <- list(recent_n=8L,alpha=.5,minimum_matches=12L,minimum_ess=8)
  hashes <- list(input=digest::digest(file=input_path,algo="sha256"))
  y <- estimate_recent_venue_goals(h,x$fixture,unlist(x$target_ids),c,hashes,root,p)
  expect_s3_class(y$rates,"tbl_df");expect_s3_class(y$parameters,"tbl_df")
  expect_equal(y$parameters$lambda_home,1.060416666666667)
  expect_equal(y$parameters$lambda_away,1.304166666666667)
  expect_equal(y$rates$matches,c(30L,30L))
  expect_equal(y$rates$recent_matches,c(8L,8L))
  expect_identical(y,estimate_recent_venue_goals(h,x$fixture,unlist(x$target_ids),c,hashes,root,p))
  expect_error(estimate_recent_venue_goals(h[0,],x$fixture,unlist(x$target_ids),c,hashes,root,p),"Explicit")
  expect_error(estimate_recent_venue_goals(h,x$fixture,unlist(x$target_ids),NULL,hashes,root,p),"Explicit")
  expect_error(estimate_recent_venue_goals(h,x$fixture,unlist(x$target_ids),c,hashes,root,list()),"policy")
})
