test_that("optional DC protection retains original choices and BD roles", {
 bd<-c(win=.60,draw=.30,lose=.10);dc<-c(win=.20,draw=.25,lose=.55)
 x<-DcProtectionChoices(bd,dc,.45)
 expect_identical(attr(x,"base_role"),1L)
 expect_identical(x[[1]],"win")
 expect_true(any(vapply(x,function(z)setequal(z,c("win","lose")),logical(1))))
 expect_true(all(lengths(x)<=2L))
 expect_identical(DcProtectionChoices(bd,bd,.45),classify_outcomes(.60,.30,.10,.45))
 all_pairs<-c(win=.46,draw=.30,lose=.24)
 expect_identical(DcProtectionChoices(all_pairs,dc,.45),classify_outcomes(.46,.30,.24,.45))
 bd2<-c(win=.40,draw=.35,lose=.25);dc2<-c(win=.25,draw=.35,lose=.40)
 z<-DcProtectionChoices(bd2,dc2,.45)
 expect_identical(attr(z,"base_role"),2L)
 expect_true(any(lengths(z)==3L))
 expect_identical(z[[1]],c("win","draw"))
 same_set<-c(win=.35,draw=.40,lose=.25)
 expect_identical(DcProtectionChoices(bd2,same_set,.45),classify_outcomes(.40,.35,.25,.45))
 triple<-c(win=.34,draw=.33,lose=.33)
 expect_identical(DcProtectionChoices(triple,dc,.45),classify_outcomes(.34,.33,.33,.45))
 expect_error(DcProtectionChoices(bd,dc[-1],.45))
 bad<-dc;bad[1]<-NA_real_;expect_error(DcProtectionChoices(bd,bad,.45))
 bad<-dc;bad[1]<-1;expect_error(DcProtectionChoices(bd,bad,.45))
})
test_that("prepared protection is normalized, ranked and bound against tampering", {
 m<-tibble::tibble(fixture_id="T:001",win=.40,draw=.35,lose=.25)
 dc<-tibble::tibble(fixture_id="T:001",outcome=c("W","D","L"),probability=c(.25,.35,.40))
 cutoff<-list(issue_id="T",cutoff_utc=as.POSIXct("2026-10-04",tz="UTC"))
 s<-prepare_outcome_selections(m,.45,dc)
 expect_true(any(s$n_outcomes==3L))
 expect_true(all(s$base_role==2L))
 expect_equal(s$coverage_probability[s$n_outcomes==3L],1)
 r<-rank_outcome_selections(s,cutoff)
 expect_identical(attr(r,"dc_protection"),dc)
 expect_silent(.parlay_ranked_validate_receipt(r))
 attr(r,"dc_protection")<-NULL
 expect_error(.parlay_ranked_validate_receipt(r),"dc_protection")
 attr(s,"dc_protection")<-NULL
 expect_error(rank_outcome_selections(s,cutoff),"recomputed")
 bad<-dc;bad$fixture_id<-"T:002"
 expect_error(prepare_outcome_selections(m,.45,bad),"universe")
 expect_error(prepare_outcome_selections(m,.45,dc[-1,]))
})
