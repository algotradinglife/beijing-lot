test_that("FM16 extends equal-distance shells by either-side threshold", {
  cutoff <- list(issue_id="26101",cutoff_utc=as.POSIXct("2026-10-03 16:30:00",tz="UTC"))
  g <- tibble::tibble(home_goals=pmax(-3:3,0L),away_goals=pmax(3:-3,0L),probability=c(.02,.06,.12,.3,.25,.15,.1))
  base <- list(grid=g,cutoff=cutoff)
  review <- list(decision="apply",center_mode="single",base_hash=beidan:::.score_margin_hash(g),cutoff_utc="2026-10-03T16:30:00Z",reason="Independent distribution",counterevidence="Uncertain lineups")
  policy <- list(max_radius=2L,threshold=.1,coefficient=.3,tie_tolerance=1e-12,dual_gap=.01)
  z <- BuildFmTailJudgement(base,review,"quote-8",cutoff,policy)
  expect_identical(z,BuildFmTailJudgement(base,review,"quote-8",policy=policy))
  expect_identical(z$center,0L);expect_identical(z$radius,2L)
  expect_identical(z$core_margins,-2:2);expect_true(all(z$shells$accepted))
  expect_equal(z$shells$left_probability,c(.12,.06));expect_equal(z$shells$right_probability,c(.25,.15))
  expect_equal(z$normalizer,.916);expect_equal(z$core_mass,.88)
  expect_equal(sum(z$judgement$bins$target_mass),1)
  expect_equal(z$judgement$bins$target_mass[z$judgement$bins$min_margin==-2],.06/.916)
  expect_identical(z,BuildFmTailJudgement(base,review,"quote-8",cutoff,policy))
  expect_equal(z$judgement$bins$min_margin[-1],head(z$judgement$bins$max_margin,-1)+1)
  gg<-g;gg$home_goals<-g$away_goals;gg$away_goals<-g$home_goals
  rr<-review;rr$base_hash<-beidan:::.score_margin_hash(gg)
  reflected<-BuildFmTailJudgement(list(grid=gg,cutoff=cutoff),rr,"quote-8",cutoff,policy)
  expect_equal(reflected$judgement$bins$target_mass,rev(z$judgement$bins$target_mass))
  shifted<-g;shifted$home_goals<-g$home_goals+2L
  rr$base_hash<-beidan:::.score_margin_hash(shifted)
  zz<-BuildFmTailJudgement(list(grid=shifted,cutoff=cutoff),rr,"quote-8",cutoff,policy)
  expect_identical(zz$center,2L);expect_identical(zz$core_margins,0:4)
  expect_equal(zz$judgement$bins$target_mass,z$judgement$bins$target_mass)
})

test_that("FM16 stops inner failed shells, respects cap and treats exact ten percent as core", {
  c<-list(issue_id="26101",cutoff_utc=as.POSIXct("2026-10-03 16:30:00",tz="UTC"))
  p<-list(max_radius=2L,threshold=.1,coefficient=.3,tie_tolerance=1e-12,dual_gap=.01)
  g<-tibble::tibble(home_goals=pmax(-3:3,0L),away_goals=pmax(3:-3,0L),probability=c(.1,.11,.09,.4,.09,.11,.1))
  r<-list(decision="apply",center_mode="single",base_hash=beidan:::.score_margin_hash(g),cutoff_utc="2026-10-03T16:30:00Z",reason="Core",counterevidence="Missing")
  z<-BuildFmTailJudgement(list(grid=g,cutoff=c),r,"e",c,p)
  expect_identical(z$radius,0L);expect_equal(nrow(z$shells),1);expect_false(z$shells$accepted)
  g$probability<-c(.05,.1,.2,.35,.2,.05,.05);r$base_hash<-beidan:::.score_margin_hash(g)
  z<-BuildFmTailJudgement(list(grid=g,cutoff=c),r,"e",c,p)
  expect_identical(z$radius,2L)
  z0<-BuildFmTailJudgement(list(grid=g,cutoff=c),r,"e",c,modifyList(p,list(max_radius=0L)))
  expect_identical(z0$radius,0L);expect_equal(nrow(z0$shells),0)
  sparse<-g[c(1,3,4,5,7),];sparse$probability<-c(.1,.2,.4,.2,.1);r$base_hash<-beidan:::.score_margin_hash(sparse)
  zs<-BuildFmTailJudgement(list(grid=sparse,cutoff=c),r,"e",c,p)
  expect_identical(zs$radius,1L)
  expect_equal(zs$judgement$bins$target_mass[zs$judgement$bins$min_margin %in% c(-2,2)],c(0,0))
  single<-tibble::tibble(home_goals=0L,away_goals=0L,probability=1);r$base_hash<-beidan:::.score_margin_hash(single)
  expect_equal(BuildFmTailJudgement(list(grid=single,cutoff=c),r,"e",c,p)$core_mass,1)
})

test_that("FM16 rejects broken bindings and preserves unresolved or tied grids", {
  c<-list(issue_id="26101",cutoff_utc=as.POSIXct("2026-10-03 16:30:00",tz="UTC"))
  p<-list(max_radius=2L,threshold=.1,coefficient=.3,tie_tolerance=1e-12,dual_gap=.01)
  g<-tibble::tibble(home_goals=0:2,away_goals=0L,probability=c(.3,.4,.3));b<-list(grid=g,cutoff=c)
  r<-list(decision="apply",center_mode="single",base_hash=beidan:::.score_margin_hash(g),cutoff_utc="2026-10-03T16:30:00Z",reason="Core",counterevidence="Missing")
  rr<-r;rr$decision<-"retain"
  expect_identical(BuildFmTailJudgement(b,rr,"e",c,p)$branch,"retained_review")
  gt<-g;gt$probability<-c(.4,.4,.2);rr<-r;rr$base_hash<-beidan:::.score_margin_hash(gt)
  expect_identical(BuildFmTailJudgement(list(grid=gt,cutoff=c),rr,"e",c,p)$branch,"retained_mode_tie")
  expect_error(BuildFmTailJudgement(b,r,"e",NULL,p))
  expect_error(BuildFmTailJudgement(modifyList(b,list(cutoff=list(issue_id="26101",cutoff_utc=c$cutoff_utc+1))),r,"e",c,p),"cutoff")
  rr<-r;rr$base_hash<-"wrong";expect_error(BuildFmTailJudgement(b,rr,"e",c,p),"binding")
  rr<-r;rr$cutoff_utc<-"2026-10-04T16:30:00Z";expect_error(BuildFmTailJudgement(b,rr,"e",c,p),"cutoff")
  rr$cutoff_utc<-"bad";expect_error(BuildFmTailJudgement(b,rr,"e",c,p),"UTC")
  expect_error(BuildFmTailJudgement(b,r,"",c,p))
  expect_error(BuildFmTailJudgement(b,r,"e",c,modifyList(p,list(max_radius=3L))))
  expect_error(BuildFmTailJudgement(b,r,"e",c,modifyList(p,list(coefficient=0))))
  expect_error(BuildFmTailJudgement(modifyList(b,list(handicap=-2)),r,"e",c,p),"Ticket")
  gg<-g;gg$probability[1]<-NA_real_;expect_error(BuildFmTailJudgement(list(grid=gg,cutoff=c),r,"e",c,p))
  gg<-g;gg$home_goals[1]<-.5;expect_error(BuildFmTailJudgement(list(grid=gg,cutoff=c),r,"e",c,p))
  gg<-g;gg$probability[1]<-.2;expect_error(BuildFmTailJudgement(list(grid=gg,cutoff=c),r,"e",c,p),"normalized")
  gg<-dplyr::bind_rows(g,g[1,]);expect_error(BuildFmTailJudgement(list(grid=gg,cutoff=c),r,"e",c,p),"Unique")
  expect_error(BuildFmTailJudgement(list(grid=g[0,],cutoff=c),r,"e",c,p))
})

