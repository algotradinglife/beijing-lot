  r$centers<-c(0L,2L);expect_error(BuildFmTailJudgement(b,r,"e",cutoff,p),"adjacent")
  r$center_mode<-"auto";expect_error(BuildFmTailJudgement(b,r,"e",cutoff,modifyList(p,list(dual_gap=NULL),keep.null=TRUE)),"explicit")
})

test_that("FM16 auto dual threshold, ambiguous modes and retain are explicit", {
  cutoff<-list(issue_id="26101",cutoff_utc=as.POSIXct("2026-10-03 16:30:00",tz="UTC"))
  p<-list(max_radius=2L,threshold=.1,coefficient=.3,tie_tolerance=1e-12,dual_gap=.01)
  for(v in list(c(.15,.35,.34,.16),c(.15,.3501,.3399,.16),c(.15,.35,.35,.15),c(.35,.15,.35,.15),c(.3,.3,.3,.1))) {
    g<-tibble::tibble(home_goals=0:3,away_goals=0L,probability=v)
    r<-list(decision="apply",center_mode="auto",base_hash=beidan:::.score_margin_hash(g),cutoff_utc="2026-10-03T16:30:00Z",reason="Boundary",counterevidence="Unresolved")
    z<-BuildFmTailJudgement(list(grid=g,cutoff=cutoff),r,"e",cutoff,p)
    if(identical(v,c(.15,.35,.34,.16))||identical(v,c(.15,.35,.35,.15))) expect_identical(z$centers,1:2)
    if(identical(v,c(.15,.3501,.3399,.16))) expect_identical(z$centers,1L)
    if(identical(v,c(.35,.15,.35,.15))||identical(v,c(.3,.3,.3,.1))) expect_identical(z$branch,"retained_mode_tie")
    r$decision<-"retain";expect_identical(BuildFmTailJudgement(list(grid=g,cutoff=cutoff),r,"e",cutoff,p)$branch,"retained_review")
  }
})
