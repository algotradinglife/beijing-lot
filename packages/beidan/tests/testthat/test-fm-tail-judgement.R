test_that("FM16 adjacent dual centers expand the interval symmetrically", {
  cutoff <- list(issue_id="26101",cutoff_utc=as.POSIXct("2026-10-03 16:30:00",tz="UTC"))
  g <- tibble::tibble(home_goals=pmax(-3:4,0L),away_goals=pmax(3:-4,0L),probability=c(.02,.06,.12,.23,.225,.15,.12,.075))
  b <- list(grid=g,cutoff=cutoff)
  r <- list(decision="apply",center_mode="auto",base_hash=beidan:::.score_margin_hash(g),cutoff_utc="2026-10-03T16:30:00Z",reason="Adjacent uncertainty",counterevidence="Hypothesis only")
  p <- list(max_radius=2L,threshold=.1,coefficient=.3,tie_tolerance=1e-12,dual_gap=.01)
  z <- BuildFmTailJudgement(b,r,"e",cutoff,p)
  expect_identical(z$centers,0:1);expect_identical(z$branch,"dual_center_tail")
  expect_identical(z$core_margins,-2:3);expect_identical(z$radius,2L)
  expect_equal(z$core_mass,.905);expect_equal(z$normalizer,.9335)
  expect_equal(sum(z$judgement$bins$target_mass),1)
  gg<-g;gg$home_goals<-g$away_goals;gg$away_goals<-g$home_goals;rr<-r;rr$base_hash<-beidan:::.score_margin_hash(gg)
  zz<-BuildFmTailJudgement(list(grid=gg,cutoff=cutoff),rr,"e",cutoff,p)
  expect_identical(zz$centers,-1:0);expect_identical(zz$core_margins,-3:2)
  expect_equal(zz$judgement$bins$target_mass,rev(z$judgement$bins$target_mass))
  r$center_mode<-"single";zs<-BuildFmTailJudgement(b,r,"e",cutoff,p);expect_identical(zs$core_margins,-2:2)
