test_that("Beidan reference SP crosses the R/Python boundary without price substitution", {
  python <- Sys.getenv("RETICULATE_PYTHON")
  skip_if(!nzchar(python),"explicit project interpreter required")
  backend <- python_backend(python)
  schedule <- tibble::tibble(issue_id="25053",slot=1L,fixture_key="25053:1",
    provider_id_nowscore="123",handicap=0,
    kickoff_at=lubridate::ymd_hms("2026-09-27 01:00:00",tz="Asia/Shanghai"))
  path <- test_path("fixtures","prematch_sp","reference.html")
  pages <- list(body=readBin(path,"raw",n=file.info(path)$size),observed_at="2026-09-26T23:00:00+08:00")
  x <- fetch_issue_prematch_sp(schedule,tempfile(),backend,pages=pages)
  expect_s3_class(x,"tbl_df")
  expect_silent(match_validate_table(x,"prematch_sp"))
  expect_identical(names(x),match_table_schemas()$prematch_sp$columns)
  expect_equal(x$sp_raw[match(c("W","D","L"),x$outcome)],c(2.5,3.4,12))
  expect_identical(lubridate::tz(x$quote_at),"Asia/Shanghai")
  expect_equal(format(x$quote_at[1],"%H:%M"),"23:00")
  expect_true(file.exists(attr(x,"receipt_path")))
  # Valuation uses the existing single-SP transform, while captured raw remains12.
  tid <- parlay_physical_ticket_key("25053:1",3L)
  tickets <- tibble::tibble(ticket_id=tid,group_id="g",probability=.2,sp_product_est=NA_real_,ev_net_est=NA_real_)
  legs <- tibble::tibble(ticket_id=tid,fixture_id="25053:1",outcome="L")
  cutoff <- list(issue_id="25053",cutoff_utc=lubridate::with_tz(lubridate::ymd_hms("2026-09-26 23:01:00",tz="Asia/Shanghai"),"UTC"))
  valued <- parlay_value_tickets(tickets,legs,x,cutoff,10,4.5,2,.65)
  expect_equal(valued$sp_product_est,4.5)
  expect_equal(valued$ev_net_est,.2*2*.65*4.5-2)
  cutoff$cutoff_utc <- cutoff$cutoff_utc-lubridate::dminutes(2)
  expect_true(is.na(parlay_value_tickets(tickets,legs,x,cutoff,10,4.5,2,.65)$ev_net_est))
  schedule$kickoff_at <- schedule$kickoff_at-lubridate::dhours(2)
  y <- fetch_issue_prematch_sp(schedule,tempfile(),backend,pages=pages)
  expect_equal(nrow(y),0L)
  expect_silent(match_validate_table(y,"prematch_sp"))
  expect_s3_class(y$quote_at,"POSIXct")
  expect_identical(attr(y,"diagnostics")$reason,"already_kicked_off")
  expect_error(fetch_issue_prematch_sp(schedule[0,],tempfile(),backend),"at least")
  expect_error(fetch_issue_prematch_sp(schedule,tempfile(),backend,timeout=0))
  expect_error(fetch_issue_prematch_sp(schedule,tempfile(),backend,pages=list(body="x",observed_at="x")),"raw")
})

test_that("research reference SP explicitly ignores closure but keeps observed state", {
  backend <- python_backend(file.path(rprojroot::find_root(rprojroot::has_file("packages/beidan/DESCRIPTION")),".venv/bin/python"))
  schedule <- tibble::tibble(issue_id="25053",slot=1L,fixture_key="25053:1",
    provider_id_nowscore="123",handicap=0,
    kickoff_at=lubridate::ymd_hms("2026-09-27 01:00:00",tz="Asia/Shanghai"))
  path <- test_path("fixtures","prematch_sp","reference.html")
  text <- rawToChar(readBin(path,"raw",n=file.info(path)$size))
  text <- sub('cansale="true"','cansale="false"',text,fixed=TRUE)
  text <- sub("00:55","截止",text,fixed=TRUE)
  body <- charToRaw(paste0('<script>M[1][4]=0;</script>',text))
  pages <- list(body=body,observed_at="2026-09-26T23:00:00+08:00")
  live <- fetch_issue_prematch_sp(schedule,tempfile(),backend,pages=pages)
  research <- fetch_issue_prematch_sp(schedule,tempfile(),backend,pages=pages,research_only=TRUE)
  expect_identical(nrow(live),0L)
  expect_identical(nrow(research),3L)
  expect_equal(research$sp_raw[match(c("W","D","L"),research$outcome)],c(2.5,3.4,12))
  expect_identical(attr(research,"research_only"),TRUE)
  receipt <- jsonlite::read_json(attr(research,"receipt_path"))
  expect_identical(receipt$research_only,TRUE)
  expect_identical(format(research$quote_at[1],"%H:%M",tz="Asia/Shanghai"),"23:00")
  expect_error(fetch_issue_prematch_sp(schedule,tempfile(),backend,research_only=1),"flag")
  pages$body <- charToRaw(text)
  missing <- fetch_issue_prematch_sp(schedule,tempfile(),backend,pages=pages,research_only=TRUE)
  expect_identical(nrow(missing),0L)
  expect_identical(attr(missing,"diagnostics")$reason,"not_observed_scheduled")
})
