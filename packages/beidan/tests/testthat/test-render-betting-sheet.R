test_that("evaluation sheets preserve exact owned tickets frozen SP and independent outcomes", {
  e <- AllocationFixture();a <- AllocateParlayBudget(e,8,"probability");f <- AllocationCatalog(e)
  view <- BuildEvaluationBettingSheetView(a,f)
  expect_setequal(view$tickets$ticket_id,a$purchases$ticket_id)
  expect_equal(sum(view$groups$new_cost_cny),8)
  expect_equal(nrow(view$legs),4);expect_equal(nrow(view$options),9)
  expect_true(all(view$options$sp_raw==3));expect_true(all(view$depth$group_status=="PENDING"))
  o <- AllocationObservation(e);o$settlements <- match_typed_empty("settlements")
  v <- BuildEvaluationBettingSheetView(a,f,o)
  expect_true(any(v$options$result));expect_true(all(is.na(v$options$settled_sp)))
  expect_equal(sum(v$depth$group_status=="HIT"),1)
  expect_true(all(v$returns$status=="PENDING"))
  expect_identical(view$tickets,v$tickets)
  bad <- f;bad$observed_at[1] <- e$cutoff$cutoff_utc
  expect_error(BuildEvaluationBettingSheetView(a,bad),"before cutoff")
  expect_error(BuildEvaluationBettingSheetView(a,f[-1,]),"missing")
  expect_error(BuildEvaluationBettingSheetView(a,dplyr::bind_rows(f,f[1,])))
  empty <- BuildEvaluationBettingSheetView(AllocateParlayBudget(e,0),f)
  expect_equal(nrow(empty$tickets),0);expect_type(empty$options$sp_raw,"double")
})
test_that("render rejects malformed paths ledgers and receipts before subprocess", {
  e <- AllocationFixture();a <- AllocateParlayBudget(e,8);view <- BuildEvaluationBettingSheetView(a,AllocationCatalog(e))
  path <- tempfile(fileext=".html");writeLines("existing",path)
  on.exit(unlink(path))
  expect_error(RenderBettingSheet(view,path,"/missing"),"existing")
  expect_identical(readLines(path),"existing")
  expect_error(RenderBettingSheet(view,tempfile(),"/missing"),"executable")
  bad <- view;bad$tickets$cost_cny[1] <- 4
  expect_error(RenderBettingSheet(bad,tempfile(),Sys.which("sh")),"receipt")
  bad$receipt <- NULL
  expect_error(RenderBettingSheet(bad,tempfile(),Sys.which("sh")),"ledger")
  empty <- BuildEvaluationBettingSheetView(AllocateParlayBudget(e,0),AllocationCatalog(e))
  expect_error(RenderBettingSheet(empty,tempfile(),Sys.which("sh")),"purchased")
  expect_error(RenderBettingSheet(view,tempfile(),Sys.which("false")),"render failed")
})
test_that("bundled template renders escaped exact tickets and reconciled duplex CSV", {
  quarto <- Sys.which("quarto")
  skip_if(!nzchar(quarto),"Quarto runtime unavailable")
  e <- AllocationFixture();view <- BuildEvaluationBettingSheetView(AllocateParlayBudget(e,8),AllocationCatalog(e))
  path <- tempfile(fileext=".html");on.exit(unlink(path))
  result <- RenderBettingSheet(view,path,quarto,title="Title <script>alert(1)</script>")
  html <- paste(readLines(path,warn=FALSE),collapse="\n")
  expect_true(grepl("Title &lt;script&gt;alert(1)&lt;/script&gt;",html,fixed=TRUE))
  expect_false(grepl("<script>alert(1)</script>",html,fixed=TRUE))
  expect_true(grepl("Home &lt;A&gt;",html,fixed=TRUE))
  expect_false(grepl('class="cell-output-error',html,fixed=TRUE))
  href <- regmatches(html,gregexpr('href="data:text/csv;charset=utf-8,[^"]+"',html))[[1]]
  csv <- lapply(href,function(s)readr::read_csv(I(utils::URLdecode(sub('"$','',sub('^href="data:text/csv;charset=utf-8,','',s)))),show_col_types=FALSE))
  expect_length(csv,3)
  expect_equal(sum(vapply(csv,function(x)sum(x$注数),numeric(1))),4)
  expect_equal(sum(vapply(csv,function(x)sum(x$金额),numeric(1))),8)
  expect_identical(result$sha256,digest::digest(file=path,algo="sha256"))
  expect_equal(tail(view$groups$cumulative_coverage,1),1-(1-.7)*(1-.37)*(1-.34))
})
