#!/usr/bin/env python3
"""Generate and execute the Issue #354 profiling notebook."""

from __future__ import annotations

import argparse
from pathlib import Path

import nbformat
from nbclient import NotebookClient


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    repo = args.repo_root.resolve()
    notebook_path = repo / "notebooks/research/low-n-selector-data/low_n_selector_data_profile.ipynb"
    notebook_path.parent.mkdir(parents=True, exist_ok=True)
    (repo / "docs/research/figures").mkdir(parents=True, exist_ok=True)

    cells = [
        nbformat.v4.new_markdown_cell(
            "# Issue #354 — strictly-prior low-N Top-2 selector data\n\n"
            "This executed notebook profiles the outcome-separated 10h feature panel. "
            "2017–2021 are expanding OOF rows; 2022–2024 are exposed transfer rows "
            "generated by a model frozen through 2021."
        ),
        nbformat.v4.new_code_cell(
            "from pathlib import Path\n"
            "import json\n"
            "import matplotlib.pyplot as plt\n"
            "import numpy as np\n"
            "import pandas as pd\n"
            "repo = Path.cwd()\n"
            "features = pd.read_parquet(repo / 'results/low_n_selector_data/features/selector_features.parquet')\n"
            "labels = pd.read_parquet(repo / 'results/low_n_selector_data/labels/selector_labels.parquet')\n"
            "coverage = pd.read_csv(repo / 'results/low_n_selector_data/analysis/coverage.csv')\n"
            "parity = pd.read_csv(repo / 'results/low_n_selector_data/analysis/accepted_surface_parity.csv')\n"
            "freeze = json.loads((repo / 'results/low_n_selector_data/FREEZE_RECEIPT.json').read_text())\n"
            "len(features), len(labels), freeze['feature_frame_sha256']"
        ),
        nbformat.v4.new_markdown_cell("## Coverage and completeness"),
        nbformat.v4.new_code_cell(
            "coverage.assign(label_rate=lambda x: x.label_available / x.fixtures)"
        ),
        nbformat.v4.new_code_cell(
            "missing = (features.isna().mean() * 100).sort_values(ascending=False).rename('missing_pct')\n"
            "missing.to_frame().head(20)"
        ),
        nbformat.v4.new_markdown_cell("## Top-2 calibration by year"),
        nbformat.v4.new_code_cell(
            "panel = features.merge(labels[['issue','match_idx','label_available','top2_hit']], "
            "on=['issue','match_idx'], validate='one_to_one')\n"
            "settled = panel[panel.label_available].copy()\n"
            "settled['top2_hit_float'] = settled.top2_hit.astype(float)\n"
            "annual = settled.groupby('issue_year').agg("
            "issues=('issue','nunique'), fixtures=('match_idx','size'), "
            "mean_retained=('retained_mass','mean'), actual_top2=('top2_hit_float','mean'), "
            "mean_books=('n_available_books','mean')).reset_index()\n"
            "annual['actual_minus_predicted'] = annual.actual_top2 - annual.mean_retained\n"
            "annual"
        ),
        nbformat.v4.new_code_cell(
            "fig, ax = plt.subplots(figsize=(9, 4.8))\n"
            "ax.plot(annual.issue_year, annual.mean_retained, marker='o', label='Mean predicted Top-2 coverage')\n"
            "ax.plot(annual.issue_year, annual.actual_top2, marker='o', label='Actual Top-2 coverage')\n"
            "ax.axvline(2021.5, color='black', linestyle='--', alpha=.5, label='Freeze before 2022')\n"
            "ax.set(title='Issue #354 Top-2 calibration by year', xlabel='Year', ylabel='Probability / hit rate', ylim=(.70,.78))\n"
            "ax.grid(alpha=.2); ax.legend(); fig.tight_layout()\n"
            "fig.savefig(repo / 'docs/research/figures/issue_354_top2_calibration.png', dpi=160)\n"
            "plt.show()"
        ),
        nbformat.v4.new_markdown_cell("## Probability distribution and calibration bins"),
        nbformat.v4.new_code_cell(
            "settled['retained_bin'] = pd.cut(settled.retained_mass, bins=np.linspace(.45,1,12), include_lowest=True)\n"
            "calibration = settled.groupby(['issue_year','retained_bin'], observed=True).agg("
            "fixtures=('match_idx','size'), predicted=('retained_mass','mean'), actual=('top2_hit_float','mean')).reset_index()\n"
            "calibration['residual'] = calibration.actual - calibration.predicted\n"
            "calibration.head(20)"
        ),
        nbformat.v4.new_code_cell(
            "fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))\n"
            "for year, group in settled.groupby('issue_year'):\n"
            "    axes[0].hist(group.retained_mass, bins=30, density=True, histtype='step', label=str(year))\n"
            "for year, group in calibration.groupby('issue_year'):\n"
            "    axes[1].plot(group.predicted, group.actual, marker='.', label=str(year))\n"
            "axes[1].plot([.45,1],[.45,1], color='black', linestyle='--', alpha=.5)\n"
            "axes[0].set(title='Retained-mass distribution', xlabel='Top-2 retained mass', ylabel='Density')\n"
            "axes[1].set(title='Binned Top-2 calibration', xlabel='Predicted', ylabel='Actual')\n"
            "axes[0].legend(ncol=2, fontsize=8); axes[1].legend(ncol=2, fontsize=8)\n"
            "for ax in axes: ax.grid(alpha=.2)\n"
            "fig.tight_layout(); fig.savefig(repo / 'docs/research/figures/issue_354_panel_profile.png', dpi=160)\n"
            "plt.show()"
        ),
        nbformat.v4.new_markdown_cell("## Source parity and temporal assertions"),
        nbformat.v4.new_code_cell("parity"),
        nbformat.v4.new_code_cell(
            "assert set(features.issue_year) == set(range(2017, 2025))\n"
            "assert (features.train_year_max < features.issue_year).all()\n"
            "assert set(features.loc[features.issue_year >= 2022, 'train_year_max']) == {2021}\n"
            "assert set(features.loc[features.issue_year >= 2022, 'calibration_history_max_year']) == {2021}\n"
            "assert not {'result_code','top2_hit','winning_sp','settlement_sp'} & set(features.columns)\n"
            "assert features.isna().sum().sum() == 0\n"
            "'All notebook assertions passed.'"
        ),
        nbformat.v4.new_markdown_cell(
            "## Decision boundary\n\n"
            "This notebook establishes data readiness only. It does not select S1–S3, "
            "inspect transfer-year performance to tune parameters, or authorize a betting candidate."
        ),
    ]
    notebook = nbformat.v4.new_notebook(
        cells=cells,
        metadata={"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}},
    )
    client = NotebookClient(notebook, timeout=600, kernel_name="python3", resources={"metadata": {"path": str(repo)}})
    client.execute()
    nbformat.write(notebook, notebook_path)
    print(notebook_path)


if __name__ == "__main__":
    main()
