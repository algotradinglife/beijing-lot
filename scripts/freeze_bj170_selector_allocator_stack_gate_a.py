def relevant_shards(kind: str) -> list[Path]:
    # #167's accepted writer preserves generation order, not global lexical
    # selector order.  A shard's first/last keys therefore cannot safely be
    # used as a range index (one target selector can occur between them in a
    # non-monotone shard sequence).  Read every manifest-bound shard and filter
    # rows by the exact three selector IDs; the source hash verification above
    # makes this bounded full scan deterministic and fail-closed.
    paths = [
        GATE_A / row["filename"]
        for row in read_csv(GATE_A / "shard_index.csv")
        if row["kind"] == kind
    ]
    if not paths:
        raise RuntimeError(f"no relevant {kind} shards")
    return paths


def load_frozen_inputs() -> tuple[list[dict[str, str]], list[dict[str, str]], list[dict[str, str]], list[dict[str, str]]]:
    aliases = selector_aliases()
    selector_grid = [row for row in read_csv(GATE_A / "selector_grid.csv") if row["selector_id"] in aliases]
    if {row["selector_id"] for row in selector_grid} != set(aliases):
        raise RuntimeError("frozen selector registry is incomplete")

    allocation_grid = read_csv(GATE_A / "allocation_grid.csv")
    wanted_keys = {arm[-1] for arm in ARMS}
    allocations = [row for row in allocation_grid if row["effective_parameter_key"] in wanted_keys]
    if {row["effective_parameter_key"] for row in allocations} != wanted_keys or len(allocations) != 3:
        raise RuntimeError("frozen allocation registry is incomplete or ambiguous")

    census = [row for row in read_csv(GATE_A / "selector_census.csv") if row["selector_id"] in aliases]
    if len(census) != 348 * 3:
        raise RuntimeError(f"selector census row drift: {len(census)}")

    identities: list[dict[str, str]] = []
    for path in relevant_shards("selector_identities"):
        with gzip.open(path, "rt", newline="", encoding="utf-8") as handle:
            identities.extend(row for row in csv.DictReader(handle) if row["selector_id"] in aliases)
    identities.sort(key=lambda row: (row["selector_id"], row["issue_instance"], row["portfolio_id"], int(row["selector_rank"])))
    expected = sum(int(row["selected_identity_count"]) for row in census)
    if len(identities) != expected:
        raise RuntimeError(f"identity census drift: rows={len(identities)} expected={expected}")

    wanted_identity_keys = {(row["selector_id"], row["issue_instance"], row["portfolio_id"]) for row in identities}
    roles: list[dict[str, str]] = []
    for path in relevant_shards("selector_role_vectors"):
        with gzip.open(path, "rt", newline="", encoding="utf-8") as handle:
            roles.extend(
                row for row in csv.DictReader(handle)
                if (row["selector_id"], row["issue_instance"], row["portfolio_id"]) in wanted_identity_keys
            )
    roles.sort(key=lambda row: (row["selector_id"], row["issue_instance"], row["portfolio_id"], int(row["selection_rank"])))
    if len(roles) != len(identities) * 7:
        raise RuntimeError(f"role ledger drift: rows={len(roles)} expected={len(identities) * 7}")
    return selector_grid, allocations, census, identities, roles


def role_product_weights(role_rows: Sequence[dict[str, str]], weight_source: str) -> tuple[float, ...]:
    columns = (
        ("q_weight3", "q_weight1", "q_weight0")
        if weight_source == "Q_WEIGHT"
        else ("p_model3", "p_model1", "p_model0")
    )
    weights = [1.0]
    for role in role_rows:
        next_weights: list[float] = []
        probabilities = tuple(float(role[column]) for column in columns)
        if any(not math.isfinite(value) or value < 0 for value in probabilities):
            raise RuntimeError("non-finite or negative probability in frozen role vector")
        for prefix in weights:
            for probability in probabilities:
                next_weights.append(prefix * probability)
        weights = next_weights
    if len(weights) != FULL_K or sum(weights) <= 0:
        raise RuntimeError("invalid seven-leg ticket weights")
    return tuple(weights)


class FrozenAllocator:
    """Thin binding to the exact accepted #145 allocator source."""

    def __init__(self, root: Path = ROOT):
        source = root / "scripts" / "bj145_fast_alloc.cpp"
        if sha256_file(source) != EXPECTED_ALLOCATOR_SHA256:
            raise RuntimeError("frozen allocator source hash drift")
        scratch = root / ".scratch"
        scratch.mkdir(exist_ok=True)
        self._build = tempfile.TemporaryDirectory(prefix="bj170-allocator-", dir=scratch)
        so = Path(self._build.name) / "bj145_fast_alloc.so"
        env = dict(os.environ, TMPDIR=self._build.name, TEMP=self._build.name, TMP=self._build.name)
        subprocess.run(
            ["g++", "-O3", "-std=c++17", "-shared", "-fPIC", str(source), "-o", str(so)],
            check=True,
            env=env,
        )
        self.lib = ctypes.CDLL(str(so))
        self.lib.bj145_code_aggregate_grid.argtypes = [
            ctypes.POINTER(ctypes.c_double), ctypes.c_int, ctypes.c_int,
            ctypes.POINTER(ctypes.c_int), ctypes.POINTER(ctypes.c_char_p),
            ctypes.c_int, ctypes.c_int, ctypes.c_char_p,
            ctypes.POINTER(ctypes.c_int), ctypes.c_int,
            ctypes.POINTER(ctypes.c_longlong), ctypes.POINTER(ctypes.c_longlong),
            ctypes.POINTER(ctypes.c_longlong),
        ]

    @staticmethod
    def _ptr(values: array.array, ctype):
        return ctypes.cast((ctype * len(values)).from_buffer(values), ctypes.POINTER(ctype))

    def allocate(self, weights: Sequence[float], mechanism: str, m: int, cap: int | None = None) -> tuple[int, ...]:
        mechanism_id = {"CAPPED_REPEAT": 3, "DETERMINISTIC_TOP_MASS": 4, "FULL_ENUMERATED": 5}[mechanism]
        weight_buffer = array.array("d", weights)
        truths = array.array("i", [-1])
        ms = array.array("i", [m])
        allocated = array.array("q", [0]) * FULL_K
        ignored_identity = array.array("q", [0]) * FULL_K
        ignored_hit = array.array("q", [0]) * FULL_K
        signatures = (ctypes.c_char_p * 1)(b"bj170-gate-a")
        self.lib.bj145_code_aggregate_grid(
            self._ptr(weight_buffer, ctypes.c_double), 1, FULL_K,
            self._ptr(truths, ctypes.c_int), signatures,
            mechanism_id, int(cap or 0), b"NA", self._ptr(ms, ctypes.c_int), 1,
            self._ptr(allocated, ctypes.c_longlong),
            self._ptr(ignored_identity, ctypes.c_longlong),
            self._ptr(ignored_hit, ctypes.c_longlong),
        )
        counts = tuple(int(value) for value in allocated)
        if sum(counts) != m:
            raise RuntimeError(f"native allocation count drift: {mechanism} M={m} total={sum(counts)}")
        return counts


def counts_digest(counts: Sequence[int]) -> dict[str, object]:
    values = tuple(int(value) for value in counts)
    return {
        "counts_sha256": hashlib.sha256(json.dumps(values, separators=(",", ":")).encode("utf-8")).hexdigest(),
        "ticket_count": sum(values),
        "unique_ticket_count": sum(value > 0 for value in values),
        "duplicate_ticket_count": sum(max(value - 1, 0) for value in values),
        "max_multiplicity": max(values),
    }


