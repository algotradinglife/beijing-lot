def freeze_allocations(
    identity_rows: Sequence[dict[str, object]],
    role_rows: Sequence[dict[str, object]],
    allocation_registry: Sequence[dict[str, str]],
    allocator: FrozenAllocator,
) -> list[dict[str, object]]:
    roles_by_identity: dict[tuple[str, str, str], list[dict[str, object]]] = defaultdict(list)
    for role in role_rows:
        roles_by_identity[(str(role["selector_id"]), str(role["issue_instance"]), str(role["portfolio_id"]))].append(role)
    allocation_by_key = {row["effective_parameter_key"]: row for row in allocation_registry}
    full_digest = counts_digest((1,) * FULL_K)
    rows: list[dict[str, object]] = []
    for identity in identity_rows:
        key = (str(identity["selector_id"]), str(identity["issue_instance"]), str(identity["portfolio_id"]))
        frozen_roles = sorted(roles_by_identity[key], key=lambda row: int(str(row["selection_rank"])))
        selected_match_ids = str(identity["selected_match_ids"]).split("|")
        if len(frozen_roles) != 7 or [row["match_id"] for row in frozen_roles] != selected_match_ids:
            raise RuntimeError(f"identity/role key mismatch: {key}")
        cached_weights: dict[str, tuple[float, ...]] = {}
        for alias, weight_source, mechanism, cap, m, parameter_key in ARMS:
            source_cell = allocation_by_key[parameter_key]
            if mechanism == "FULL_ENUMERATED":
                digest = full_digest
            else:
                weights = cached_weights.setdefault(weight_source, role_product_weights(frozen_roles, weight_source))
                counts = allocator.allocate(weights, mechanism, m, None if cap == "NA" else int(cap))
                digest = counts_digest(counts)
            rows.append({
                "selector_alias": identity["selector_alias"],
                "selector_id": identity["selector_id"],
                "issue_instance": identity["issue_instance"],
                "portfolio_id": identity["portfolio_id"],
                "support_key_sha256": identity["support_key_sha256"],
                "allocation_arm": alias,
                "source_cell_id": source_cell["cell_id"],
                "effective_parameter_key": source_cell["effective_parameter_key"],
                "weight_source": weight_source,
                "mechanism": mechanism,
                "cap": cap,
                "M": m,
                "ticket_space_k": FULL_K,
                "ticket_count": digest["ticket_count"],
                "unique_ticket_count": digest["unique_ticket_count"],
                "duplicate_ticket_count": digest["duplicate_ticket_count"],
                "max_multiplicity": digest["max_multiplicity"],
                "planned_stake_yuan": int(digest["ticket_count"]) * STAKE_YUAN,
                "counts_sha256": digest["counts_sha256"],
                "allocator_sha256": EXPECTED_ALLOCATOR_SHA256,
                "outcome_boundary": OUTCOME_BOUNDARY,
            })
    return rows


