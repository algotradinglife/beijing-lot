def support_views(
    participation: Sequence[dict[str, object]], identity_rows: Sequence[dict[str, object]]
) -> tuple[list[dict[str, object]], list[dict[str, object]], list[dict[str, object]]]:
    aliases = tuple(alias for alias, _, _ in SELECTORS)
    selector_ids = {alias: selector_id for alias, selector_id, _ in SELECTORS}
    issue_counts: dict[tuple[str, str], int] = {
        (str(row["selector_alias"]), str(row["issue_instance"])): int(row["selected_identity_count"])
        for row in participation
    }
    issue_meta = {str(row["issue_instance"]): (str(row["issue"]), str(row["year"]), str(row["fold"])) for row in participation}
    all_issues = sorted(issue_meta)

    definitions: list[tuple[str, tuple[str, ...], str]] = []
    for alias in aliases:
        definitions.append((f"NATIVE_{alias}", (alias,), "NATIVE_SUPPORT"))
    for left_index in range(len(aliases)):
        for right_index in range(left_index + 1, len(aliases)):
            pair = (aliases[left_index], aliases[right_index])
            definitions.append((f"PAIRWISE_{pair[0]}__{pair[1]}", pair, "PAIRWISE_COMMON_SUPPORT"))
    definitions.append(("THREE_WAY_ALL", aliases, "THREE_WAY_COMMON_SUPPORT"))

    membership: list[dict[str, object]] = []
    registry: list[dict[str, object]] = []
    for view_id, members, view_type in definitions:
        eligible = [issue_instance for issue_instance in all_issues if all(issue_counts.get((member, issue_instance), 0) > 0 for member in members)]
        member_rows = []
        for issue_instance in eligible:
            counts = {member: issue_counts[(member, issue_instance)] for member in members}
            issue, year, fold = issue_meta[issue_instance]
            row = {
                "support_view_id": view_id,
                "support_view_type": view_type,
                "selector_aliases": "|".join(members),
                "selector_ids": "|".join(selector_ids[member] for member in members),
                "issue": issue,
                "year": year,
                "fold": fold,
                "issue_instance": issue_instance,
                "selector_identity_counts_json": json.dumps(counts, sort_keys=True, separators=(",", ":")),
                "identity_occurrence_count": sum(counts.values()),
                "support_issue_row_sha256": canonical_hash([view_id, issue_instance, counts]),
                "outcome_boundary": OUTCOME_BOUNDARY,
            }
            membership.append(row)
            member_rows.append(row["support_issue_row_sha256"])
        registry.append({
            "support_view_id": view_id,
            "support_view_type": view_type,
            "selector_aliases": "|".join(members),
            "selector_ids": "|".join(selector_ids[member] for member in members),
            "eligible_issue_count": len(eligible),
            "identity_occurrence_count": sum(int(row["identity_occurrence_count"]) for row in membership if row["support_view_id"] == view_id),
            "support_view_sha256": canonical_hash(member_rows),
            "eligibility_rule": "all listed selectors have >=1 frozen pre-outcome identity in the issue",
            "outcome_boundary": OUTCOME_BOUNDARY,
        })

    support_members: dict[str, list[dict[str, object]]] = defaultdict(list)
    for row in identity_rows:
        support_members[str(row["support_key_sha256"])].append(row)
    exact_rows = []
    for support_key, rows in sorted(support_members.items()):
        present_aliases = sorted({str(row["selector_alias"]) for row in rows}, key=aliases.index)
        exact_rows.append({
            "support_key_sha256": support_key,
            "issue_instance": rows[0]["issue_instance"],
            "selected_match_ids": rows[0]["selected_match_ids"],
            "selector_aliases": "|".join(present_aliases),
            "selector_count": len(present_aliases),
            "identity_occurrence_count": len(rows),
            "pairwise_common": "1" if len(present_aliases) >= 2 else "0",
            "three_way_common": "1" if len(present_aliases) == 3 else "0",
            "outcome_boundary": OUTCOME_BOUNDARY,
        })
    return registry, membership, exact_rows


def package_identity(stage: Path, controls: dict[str, object]) -> tuple[str, str]:
    payload_names = sorted(path.name for path in stage.iterdir() if path.is_file() and path.name not in {"CONTENT_IDENTITY.json", "SHA256SUMS.json"})
    content = {
        "contract_version": VERSION,
        "controls": controls,
        "payloads": {name: sha256_file(stage / name) for name in payload_names},
    }
    (stage / "CONTENT_IDENTITY.json").write_text(json.dumps(content, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    sums = {path.name: sha256_file(path) for path in stage.iterdir() if path.is_file() and path.name != "SHA256SUMS.json"}
    (stage / "SHA256SUMS.json").write_text(json.dumps(sums, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return sha256_file(stage / "SHA256SUMS.json"), sha256_file(stage / "CONTENT_IDENTITY.json")


