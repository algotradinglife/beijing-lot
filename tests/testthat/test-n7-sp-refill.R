testthat::test_that('refill preserves identities, excludes low prices and restores RNG', {
  cuts<-list(a='epoch');f<-list(p_W=.5,p_D=.3,p_L=.2,q_W=.5,q_D=.3,q_L=.2)
  low<-list(p_W=.8,p_D=.1,p_L=.1,q_W=.8,q_D=.1,q_L=.1)
  base<-list(cutoffs=cuts,fixtures=c(rep(list(f),9),list(low)),
    options=list(list(sleeve_id=0,fixtures=1:7),list(sleeve_id=1,fixtures=4:10)))
  part<-list(cutoffs=cuts,core_ids=0:1,opening_depths=c('0'=15,'1'=15),
    opportunity_ids=integer(),opportunity_depth=15,opportunity_stake_cny=0)
  set.seed(17);before<-.Random.seed
  z<-n7_sp_refill(base,part,cuts,1.3,2,11,100,7)
  testthat::expect_identical(.Random.seed,before)
  testthat::expect_identical(z,n7_sp_refill(base,part,cuts,1.3,2,11,100,7))
  testthat::expect_equal(z$actual,2)
  testthat::expect_equal(z$groups[[1]]$fixtures,1:7)
  testthat::expect_equal(z$groups[[1]]$sleeve_id,0)
  testthat::expect_equal(z$groups[[2]]$sleeve_id,2)
  testthat::expect_false(10 %in% z$groups[[2]]$fixtures)
  testthat::expect_length(unique(z$groups[[2]]$fixtures),7)
  all<-n7_sp_refill(base,part,cuts,1,2,11,100,7)
  testthat::expect_equal(all$attempts,0)
  testthat::expect_equal(all$groups[[2]]$fixtures,4:10)
  none<-n7_sp_refill(base,part,cuts,3,2,11,100,7)
  testthat::expect_length(none$groups,0)
  testthat::expect_equal(none$status,'BOUNDED_SHORTFALL')
  changed<-base;changed$settlement<-list(actual_rank=1)
  testthat::expect_identical(z,n7_sp_refill(changed,part,cuts,1.3,2,11,100,7))
  testthat::expect_error(n7_sp_refill(base,part,list(a='later'),1.3,2,11,100,7))
  testthat::expect_error(n7_sp_refill(base,part,cuts,1.3,1,11,100,7))
  testthat::expect_error(n7_sp_refill(base,part,cuts,1.3,2,NA,100,7))
  limited<-n7_sp_refill(base,part,cuts,1.3,3,11,1,7)
  testthat::expect_equal(limited$attempts,1)
  testthat::expect_lte(limited$actual,2)
  testthat::expect_equal(limited$status,'BOUNDED_SHORTFALL')
  scarce<-base;scarce$fixtures[8:9]<-list(low,low)
  one<-n7_sp_refill(scarce,part,cuts,1.3,2,11,100,7)
  testthat::expect_equal(one$actual,1)
  testthat::expect_equal(one$attempts,0)
  duplicate<-base;duplicate$options[[2]]$fixtures<-7:1
  testthat::expect_error(n7_sp_refill(duplicate,part,cuts,1.3,2,11,100,7))
})
