source('../../r/fundamentals_pure_baseline.R')
testthat::test_that('pure projection uses only raw grids and validates identity/cutoffs', {
 cuts <- list('001'=list('1'='2010-01-01T00:00:00Z'))
 f <- tibble::tibble(issue='001',slot=1L,provider_id='009',home='H',away='A',handicap=0,scenario='baseline')
 grid <- tibble::tibble(home_goals=c(1L,0L,0L),away_goals=c(0L,0L,1L),probability=c(.5,.2,.3),outcome=c('W','D','L'))
 control <- list(fixtures=f,scores=dplyr::cross_join(f[c('issue','slot','provider_id','scenario')],grid),cutoffs=cuts)
 market <- list(status=dplyr::mutate(f,status='READY'),grids=list('001/1'=grid),cutoffs=cuts)
 x <- pure_baseline_factors(control,market,cuts)
 testthat::expect_equal(unlist(x[c('p_W','p_D','p_L')]),c(p_W=.5,p_D=.2,p_L=.3))
 testthat::expect_identical(x$provider_id,'009')
 changed <- market;changed$grids[[1]]$probability <- c(.3,.4,.3)
 y <- pure_baseline_factors(control,changed,cuts)
 testthat::expect_equal(x[c('p_W','p_D','p_L')],y[c('p_W','p_D','p_L')])
 testthat::expect_equal(y$q_D,.4)
 testthat::expect_error(pure_baseline_factors(control,market,list()))
 bad <- market;bad$grids <- list();testthat::expect_error(pure_baseline_factors(control,bad,cuts),'grid')
 bad <- market;bad$status$provider_id <- 'wrong';testthat::expect_error(pure_baseline_factors(control,bad,cuts),'identity')
 bad <- control;bad$scores$probability[1] <- NA_real_;testthat::expect_error(pure_baseline_factors(bad,market,cuts),'grid')
 bad <- control;bad$scores$outcome[1] <- 'L';testthat::expect_error(pure_baseline_factors(bad,market,cuts),'Handicap')
 bad <- control;bad$fixtures <- dplyr::bind_rows(f,f);testthat::expect_error(pure_baseline_factors(bad,market,cuts))
 bad <- market;bad$grids[[1]]$probability <- c(1,0,0);testthat::expect_error(pure_baseline_factors(control,bad,cuts),'Positive')
 empty <- control;empty$fixtures <- f[0,];empty$scores <- control$scores[0,]
 testthat::expect_equal(nrow(pure_baseline_factors(empty,market,cuts)),0)
 testthat::expect_type(pure_baseline_factors(empty,market,cuts)$p_W,'double')
})
