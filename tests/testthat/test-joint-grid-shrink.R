source(file.path('..','..','r','joint_grid_shrink.R'))
source(file.path('..','..','r','joint_win_scale.R'))
test_that('fixed shrinkage binds cutoff, endpoints, sparse signals and allocation', {
  model<-paste(rep('a',64),collapse='')
  cut<-list(cutoff_kind='DECISION_EPOCH',cutoff_identity='x',cutoff_ts='2020-01-01T00:00:00Z',
    target_issue='001',historical_admission=FALSE,model_receipt_sha256=model)
  f<-tibble::tibble(issue='001',cell=c('a','b'),fine_score=c(.7,1.6),coarse_score=c(1.4,.8),
    fine_ready=TRUE,coarse_ready=TRUE,cutoff_identity='x')
  attr(f,'input_receipt')<-list(cutoff=cut,hash=digest::digest(f,algo='sha256'))
  expect_equal(joint_grid_shrink(f,cut,model,0)$return_ratio,c(.7,1.6))
  expect_equal(joint_grid_shrink(f,cut,model,1)$return_ratio,c(1.4,.8))
  s<-joint_grid_shrink(f,cut,model,.25)
  expect_equal(s$return_ratio,c(.875,1.4))
  t<-tibble::tibble(issue='001',ticket_id=letters[1:4],cell=rep(c('a','b'),each=2),prob=c(.6,.5,.4,.3),base_copies=1L)
  a<-joint_win_scale(t,s,cut,model,'BLEND','BOTH',.5,.8,1.2,.5,.5,2,10)
  expect_equal(a$copies,c(1,1,2,1))
  expect_error(joint_grid_shrink(f,cut,model,-.1))
  expect_error(joint_grid_shrink(f,cut,model,NA_real_))
  b<-cut;b$target_issue<-'002';expect_error(joint_grid_shrink(f,b,model,.5))
  b<-cut;b$cutoff_ts<-'2020-01-02T00:00:00Z';expect_error(joint_grid_shrink(f,b,model,.5))
  expect_error(joint_grid_shrink(f,cut,paste(rep('b',64),collapse=''),.5))
  b<-f;b$fine_score[1]<-5;expect_error(joint_grid_shrink(b,cut,model,.5))
  b<-f;attr(b,'input_receipt')<-NULL;b$coarse_ready[1]<-FALSE;b$coarse_score[1]<-NA_real_
  attr(b,'input_receipt')<-list(cutoff=cut,hash=digest::digest(b,algo='sha256'))
  expect_false(joint_grid_shrink(b,cut,model,.5)$supported[1])
  expect_true(is.na(joint_grid_shrink(b,cut,model,.5)$return_ratio[1]))
  expect_equal(joint_grid_shrink(b,cut,model,0)$return_ratio,c(.7,1.6))
  e<-f[FALSE,];attr(e,'input_receipt')<-NULL;attr(e,'input_receipt')<-list(cutoff=cut,hash=digest::digest(e,algo='sha256'))
  expect_equal(nrow(joint_grid_shrink(e,cut,model,.5)),0)
  b<-f;attr(b,'input_receipt')<-NULL;b$cell[2]<-'a';attr(b,'input_receipt')<-list(cutoff=cut,hash=digest::digest(b,algo='sha256'))
  expect_error(joint_grid_shrink(b,cut,model,.5))
  b<-f;attr(b,'input_receipt')<-NULL;b$fine_score[1]<--1;attr(b,'input_receipt')<-list(cutoff=cut,hash=digest::digest(b,algo='sha256'))
  expect_error(joint_grid_shrink(b,cut,model,.5))
  b<-f;attr(b,'input_receipt')<-NULL;b$future_label<-1e9;attr(b,'input_receipt')<-list(cutoff=cut,hash=digest::digest(b,algo='sha256'))
  changed<-joint_grid_shrink(b,cut,model,.25)
  expect_identical(joint_win_scale(t,changed,cut,model,'BLEND','BOTH',.5,.8,1.2,.5,.5,2,10),a)
})
