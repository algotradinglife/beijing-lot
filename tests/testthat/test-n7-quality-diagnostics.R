root<-normalizePath(file.path(testthat::test_path(),'../..'))
for(p in c('fundamentals_equity_curves','n7_sweet_union_summary','n7_selection_diagnostics','n7_quality_diagnostics'))source(file.path(root,'r',paste0(p,'.R')))
testthat::test_that('quality diagnostics pairs actual stake and retains initial capital', {
 rows<-tibble::tibble(issue=rep(c('a','b'),2),arm=rep(c('j','n'),each=2),seed=1,
  variant=rep(c('JOINT','NEW'),each=2),budget_cny=8,stake=4,cash=4,groups=1,
  gross=c(0,10,10,0),net=c(-4,6,6,-4),hits=c(0,1,1,0),eval_union=.3)
 funded<-rows |> dplyr::select(issue,arm,seed,stake) |> dplyr::mutate(sleeve_id='0',coverage=.3)
 membership<-tidyr::expand_grid(issue=c('a','b'),sleeve_id='0',fixture_id=1:7)
 z<-n7_quality_diagnostics(rows,funded,membership,c('a','b'),100)
 testthat::expect_equal(z$summary$net,c(2,2))
 testthat::expect_equal(z$summary$roi,c(.25,.25))
 testthat::expect_equal(z$paired$delta_net,c(0,0))
 testthat::expect_equal(sum(z$per_issue$rescued),1)
 testthat::expect_equal(sum(z$per_issue$lost),1)
 testthat::expect_equal(z$curves$equity_cny[z$curves$period==0],c(100,100))
 testthat::expect_equal(z$summary$zero_hit_issues,c(1L,1L))
 testthat::expect_equal(z$summary$longest_loss_streak,c(1,1))
 testthat::expect_equal(z$summary$mean_fixture_capital_hhi,c(1/7,1/7))
 testthat::expect_error(n7_quality_diagnostics(rows,funded,membership,c('a'),100))
 exhausted<-n7_quality_diagnostics(rows,funded,membership,c('a','b'),4)
 testthat::expect_equal(exhausted$summary$net[exhausted$summary$variant=='JOINT'],-4)
 testthat::expect_equal(exhausted$summary$funded_issues[exhausted$summary$variant=='JOINT'],1)
 testthat::expect_equal(exhausted$blocks$net[exhausted$blocks$variant=='JOINT'],-4)
 testthat::expect_equal(exhausted$per_issue$gross[exhausted$per_issue$variant=='JOINT'],c(0,0))
})
