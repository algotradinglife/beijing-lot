source('../../r/n7_selection_report.R')
testthat::test_that('report rejects stale independent checks after coherent settlement rewrite',{
 d<-tempfile();dir.create(d);withr::defer(unlink(d,recursive=TRUE))
 files<-c('predictions.csv','funded.csv','actions.csv')
 for(n in c(files,'results.csv'))writeLines('test',file.path(d,n))
 hashes<-vapply(file.path(d,files),digest::digest,character(1),file=TRUE,algo='sha256')
 jsonlite::write_json(list(files=as.list(setNames(hashes,files))),file.path(d,'plans-frozen.json'),auto_unbox=TRUE)
 fh<-digest::digest(file=file.path(d,'plans-frozen.json'),algo='sha256')
 rh<-digest::digest(file=file.path(d,'results.csv'),algo='sha256')
 r<-list(status='PASS',plans=1,freeze_sha256=fh,results_sha256=rh,labels_loaded=FALSE)
 for(n in c('allocation-replay.json','independent-check.json','evaluation-receipt.json'))jsonlite::write_json(r,file.path(d,n),auto_unbox=TRUE)
 testthat::expect_equal(n7_selection_report_inputs(d,1)$results_sha256,rh)
 testthat::expect_error(n7_selection_report_inputs(d,2))
 testthat::expect_error(n7_selection_report_inputs(d,NA))
 writeLines('changed results',file.path(d,'results.csv'))
 r$results_sha256<-digest::digest(file=file.path(d,'results.csv'),algo='sha256')
 jsonlite::write_json(r,file.path(d,'evaluation-receipt.json'),auto_unbox=TRUE)
 testthat::expect_error(n7_selection_report_inputs(d,1),'results_sha256')
 jsonlite::write_json(r,file.path(d,'independent-check.json'),auto_unbox=TRUE)
 testthat::expect_equal(n7_selection_report_inputs(d,1)$results_sha256,r$results_sha256)
 r$labels_loaded<-TRUE
 jsonlite::write_json(r,file.path(d,'allocation-replay.json'),auto_unbox=TRUE)
 testthat::expect_error(n7_selection_report_inputs(d,1),'labels_loaded')
 r$labels_loaded<-FALSE
 jsonlite::write_json(r,file.path(d,'allocation-replay.json'),auto_unbox=TRUE)
 writeLines('changed plan',file.path(d,'funded.csv'))
 testthat::expect_error(n7_selection_report_inputs(d,1))
})
