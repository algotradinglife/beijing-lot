test_that('selection rejects a changed forecast before deserializing it', {
 root <- rprojroot::find_root(rprojroot::has_file('packages/beidan/DESCRIPTION'))
 work <- tempfile();dir.create(work);on.exit(unlink(work,recursive=TRUE),add=TRUE)
 withr::local_dir(work)
 dir.create('r');file.copy(file.path(root,'r/global_dynamic_26105_select_20261019.R'),'r/global_dynamic_26105_select_20261019.R')
 out <- 'results/global-dynamic-walkforward-20261018/26105';dir.create(out,recursive=TRUE)
 writeLines('changed forecast; intentionally not RDS',file.path(out,'frozen-forecasts.rds'))
 hash <- paste(rep('a',64),collapse='')
 jsonlite::write_json(list(sha256=hash),file.path(out,'forecast-manifest.json'),auto_unbox=TRUE)
 jsonlite::write_json(list(status='FULL_IDENTICAL_REPLAY',sha256=hash),file.path(out,'forecast-replay.json'),auto_unbox=TRUE)
 context <- new.env(parent=globalenv());context$commandArgs <- function(...) c(work,'26105','freeze')
 expect_error(sys.source('r/global_dynamic_26105_select_20261019.R',envir=context),'Frozen forecast replay binding mismatch',fixed=TRUE)
 expect_false(file.exists(file.path(out,'frozen-rounds.rds')))
})
