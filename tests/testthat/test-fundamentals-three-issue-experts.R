testthat::test_that('abstaining tree grid reports explicit coverage and fixed policies', {
 d <- tibble::tibble(issue='i',slot=1:12,provider_id=as.character(1:12),home='H',away='A',
                    score=as.numeric(1:12),target=c(rep(FALSE,6),rep(TRUE,6)),base=.5)
 cuts <- list(i=as.list(stats::setNames(rep('2000-01-01T00:00:00Z',12),1:12)))
 configs <- tibble::tibble(model='one',depth=1,bucket=3)
 x <- compare_abstaining_experts(d,'TEST','score','target','base',cuts,'SAMPLE_IN_EXPLORATION_ONLY',configs)
 testthat::expect_equal(x$summary$emitted,c(12L,12L))
 testthat::expect_equal(x$summary$hits,c(12L,12L))
 testthat::expect_equal(x$leaves$probability,c(1/8,7/8))
 testthat::expect_null(x$receipt$selected_model)
 testthat::expect_false(x$receipt$deployable)
 d$score <- rep(1,12)
 flat <- compare_abstaining_experts(d,'TEST','score','target','base',cuts,'SAMPLE_IN_EXPLORATION_ONLY',configs)
 testthat::expect_equal(flat$summary$emitted,c(0L,0L))
 testthat::expect_true(all(is.na(flat$summary$accuracy)))
 testthat::expect_error(compare_abstaining_experts(d,'TEST','score','target','base',list(),'SAMPLE_IN_EXPLORATION_ONLY',configs),'cutoff')
 testthat::expect_error(compare_abstaining_experts(d,'TEST','score','target','base',cuts,'',configs),'exception')
 d$score[1] <- NA_real_
 testthat::expect_error(compare_abstaining_experts(d,'TEST','score','target','base',cuts,'SAMPLE_IN_EXPLORATION_ONLY',configs),'Invalid')
})
testthat::test_that('full scope retains all exclusions and giving-side goal features', {
 root <- normalizePath('../..');p <- file.path(root,'tests/fixtures/three_issue_experts')
 ctx <- file.path(p,'context.json')
 cuts <- jsonlite::read_json(ctx,simplifyVector=TRUE)$cutoffs
 x <- three_issue_expert_inputs(file.path(p,'review.json'),file.path(p,'acceptance.json'),ctx,cuts,root,file.path(p,"labels.json"),file.path(p,"labels-acceptance.json"))
 altered <- jsonlite::read_json(file.path(p,'review.json'),simplifyVector=TRUE)
 altered$fixtures$actual_home[1] <- altered$fixtures$actual_home[1]+1
 tmp <- tempfile(fileext='.json');on.exit(unlink(tmp))
 jsonlite::write_json(altered,tmp,auto_unbox=TRUE,dataframe='rows',digits=15)
 testthat::expect_error(three_issue_expert_inputs(tmp,file.path(p,'acceptance.json'),ctx,cuts,root,file.path(p,'labels.json'),file.path(p,'labels-acceptance.json')),'settlement')
 testthat::expect_identical(names(jsonlite::fromJSON(jsonlite::toJSON(x$receipt,auto_unbox=TRUE))$source_hashes),names(x$receipt$source_hashes))
 testthat::expect_equal(nrow(x$scope),171L)
 testthat::expect_equal(nrow(x$data),12L)
 testthat::expect_equal(sum(x$data$handicap_depth>=2),6L)
 testthat::expect_equal(x$data$draw_target,x$data$actual_home-x$data$actual_away+x$data$handicap==0)
 testthat::expect_true(all(is.finite(x$data$giving_big_win_rate[x$data$handicap_depth>=2])))
 testthat::expect_error(three_issue_expert_inputs(file.path(p,'review.json'),file.path(p,'acceptance.json'),ctx,list(),root,file.path(p,"labels.json"),file.path(p,"labels-acceptance.json")),'cutoff')
})
