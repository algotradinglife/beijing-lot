source('../../r/fundamentals_pure_report.R')
testthat::test_that('both render paths authenticate exact result bytes and canonical receipt', {
 study <- tempfile();dir.create(study)
 on.exit(unlink(study,recursive=TRUE),add=TRUE)
 result <- list(rows=list(list(gross=100,net=36,stake=64)),upstream_freeze_seal='plan')
 body <- jsonlite::toJSON(result,auto_unbox=TRUE)
 writeLines(body,file.path(study,'results.json'))
 receipt <- list(scope='PURE_BASELINE_POST_EXPOSURE_PAIRED_DIAGNOSTIC',plan_freeze_seal='plan',
  result_sha256=digest::digest(file=file.path(study,'results.json'),algo='sha256'),source_hashes=list(),implementation=list(files=list()),report_files=list())
 canonical <- as.character(jsonlite::toJSON(receipt,auto_unbox=TRUE))
 jsonlite::write_json(list(canonical_json=canonical,seal=digest::digest(canonical,algo='sha256',serialize=FALSE)),file.path(study,'plans-frozen.json'),auto_unbox=TRUE)
 paths <- file.path(study,c('results.json','plans-frozen.json'))
 archive <- list(mode='ARCHIVED_RENDER_ONLY_NOT_MODEL_REPLAY',hashes=as.list(stats::setNames(vapply(paths,digest::digest,character(1),file=TRUE,algo='sha256'),paths)))
 jsonlite::write_json(archive,file.path(study,'archive.json'),auto_unbox=TRUE)
 testthat::expect_equal(read_pure_baseline_report(study,FALSE)$result$rows$net,36)
 testthat::expect_equal(read_pure_baseline_report(study,TRUE)$result$rows$net,36)
 result$rows[[1]]$gross <- 1100;result$rows[[1]]$net <- 1036
 jsonlite::write_json(result,file.path(study,'results.json'),auto_unbox=TRUE)
 testthat::expect_error(read_pure_baseline_report(study,FALSE),'result hash')
 testthat::expect_error(read_pure_baseline_report(study,TRUE),'result hash')
 writeLines(body,file.path(study,'results.json'))
 jsonlite::write_json(list(canonical_json=paste0(canonical,' '),seal=digest::digest(canonical,algo='sha256',serialize=FALSE)),file.path(study,'plans-frozen.json'),auto_unbox=TRUE)
 testthat::expect_error(read_pure_baseline_report(study,FALSE))
 testthat::expect_error(read_pure_baseline_report(study,NA))
})
