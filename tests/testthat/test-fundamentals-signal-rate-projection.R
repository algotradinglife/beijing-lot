testthat::test_that('calibrated mass is applied once and conditional scores survive', {
  g <- tibble::tibble(home_goals=c(0,1,1,2,0),away_goals=c(0,1,0,0,1),probability=c(.1,.1,.3,.2,.3))
  z <- project_signal_rate_grid(g,0,.4,NA_real_,.5,'2010-01-01T00:00:00Z')
  testthat::expect_equal(unname(z$probabilities),c(.375,.4,.225))
  testthat::expect_equal(z$grid$probability[1:2],c(.2,.2))
  testthat::expect_equal(z$grid$probability[3]/z$grid$probability[4],1.5)
  testthat::expect_equal(sum(project_signal_rate_grid(g,0,1,NA_real_,.5,'x')$grid$probability),1)
  testthat::expect_error(project_signal_rate_grid(g,0,.4,.6,.5,'x'),'scope')
  testthat::expect_error(project_signal_rate_grid(g,0,.4,NA_real_,.5,NULL),'cutoff')
  testthat::expect_error(project_signal_rate_grid(g,0,NA_real_,NA_real_,.5,'x'),'mass')
  h <- tibble::tibble(home_goals=c(3,2,1),away_goals=c(0,0,0),probability=c(.4,.2,.4))
  z <- project_signal_rate_grid(h,-2,.3,.6,.5,'x')
  testthat::expect_equal(unname(z$probabilities),c(.5,.3,.2))
  z <- project_signal_rate_grid(h,-2,.8,.6,.5,'x')
  testthat::expect_equal(z$status,'CONFLICT_KEEP_BASELINE')
  testthat::expect_equal(z$grid$probability,h$probability)
})

testthat::test_that('whole fixture projection adjusts abstentions and validates joins', {
  cuts <- list('001'=list('1'='2010-01-01T00:00:00Z'))
  f <- tibble::tibble(issue='001',slot=1L,provider_id='x',home='H',away='A',handicap=0,scenario='baseline')
  g <- tibble::tibble(home_goals=c(0,1,0),away_goals=c(0,0,1),probability=c(.2,.5,.3),outcome=c('D','W','L'))
  control <- list(fixtures=f,scores=dplyr::mutate(g,issue='001',slot=1L,provider_id='x',scenario='baseline'),cutoffs=cuts)
  p <- dplyr::mutate(f,draw_probability=.45,draw_signal='ABSTAIN')
  h <- dplyr::mutate(f,high_probability=NA_real_,high_signal='NOT_APPLICABLE')
  z <- signal_rate_score_choices(control,p,h,cuts,.5)
  testthat::expect_equal(z$fixtures$selected,'D,W')
  testthat::expect_equal(sum(z$scores$probability[z$scores$outcome=='D']),.45)
  testthat::expect_equal(z$signals$draw_signal,'ABSTAIN')
  testthat::expect_error(signal_rate_score_choices(control,p[0,],h,cuts,.5),'identities')
  testthat::expect_error(signal_rate_score_choices(control,dplyr::bind_rows(p,p),h,cuts,.5),'Duplicate')
  testthat::expect_error(signal_rate_score_choices(control,p,h,list(),.5),'Cutoff')
})
