testthat::test_that('runner validates, exports arbitrary cohort, refuses overwrite and detects tamper',{
 root<-normalizePath(file.path('..','..'))
 withr::local_dir(root)
 parent<-tempfile('runner-test-',tmpdir=tempdir())
 dir.create(parent);parent<-normalizePath(parent);withr::defer(unlink(parent,recursive=TRUE))
 source<-file.path(parent,'input');dir.create(source)
 con<-gzfile('tests/fixtures/category_diagnostics.json.gz');archive<-jsonlite::fromJSON(con,simplifyVector=FALSE)
 packet<-jsonlite::fromJSON(archive$files[['results.json']])
 selected<-head(packet$rows$issue,2)
 for(n in c('rows','factors','features','legs','audit')) packet[[n]]<-packet[[n]][packet[[n]]$issue %in% selected,]
 jsonlite::write_json(packet,file.path(source,'results.json'),dataframe='rows',auto_unbox=TRUE,digits=NA)
 receipt<-list(scope='PURE_BASELINE_POST_EXPOSURE_PAIRED_DIAGNOSTIC',plan_freeze_seal=packet$upstream_freeze_seal,
  result_sha256=digest::digest(file=file.path(source,'results.json'),algo='sha256'),
  source_hashes=list(),report_files=list(),implementation=list(files=list()))
 canonical<-as.character(jsonlite::toJSON(receipt,auto_unbox=TRUE))
 jsonlite::write_json(list(canonical_json=canonical,seal=digest::digest(canonical,algo='sha256',serialize=FALSE)),
  file.path(source,'plans-frozen.json'),auto_unbox=TRUE)
 output<-file.path(parent,'output')
 path<-run_category_diagnostics(source,output,FALSE,root)
 v<-read_category_diagnostic_output(path)
 testthat::expect_equal(v$receipt$issues,2L)
 testthat::expect_equal(v$receipt$missed_issues,sum(packet$rows$hits==0))
 testthat::expect_true(all(v$data$summary$slice %in% c('ALL','MISSED','HIT')))
 testthat::expect_true(all(c('summary.csv','observations.csv','original_groups.csv','original_issues.csv','report.qmd','receipt.json') %in% list.files(path)))
 testthat::expect_error(run_category_diagnostics(source,output,FALSE,root))
 testthat::expect_error(run_category_diagnostics(source,file.path(parent,'absent','output'),FALSE,root))
 # Exercise thin CLI from another working directory, including paths with spaces.
 cli<-file.path(root,'scripts/diagnose_fundamentals.R')
 withr::local_dir(parent)
 testthat::expect_equal(system2(file.path(R.home('bin'),'Rscript'),c(shQuote(cli),'--help'),stdout=FALSE,stderr=FALSE),0L)
 testthat::expect_equal(system2(file.path(R.home('bin'),'Rscript'),c(shQuote(cli),'--unknown'),stdout=FALSE,stderr=FALSE),1L)
 cliout<-file.path(parent,'cli output')
 testthat::expect_equal(system2(file.path(R.home('bin'),'Rscript'),c(shQuote(cli),shQuote(normalizePath(source)),shQuote(cliout),'--no-render'),stdout=FALSE,stderr=FALSE),0L)
 testthat::expect_true(file.exists(file.path(cliout,'summary.csv')))
 testthat::expect_false(file.exists(file.path(cliout,'report.html')))
 setwd(root)
 cat('tamper',file=file.path(path,'summary.csv'),append=TRUE)
 testthat::expect_error(read_category_diagnostic_output(path))
 # Failure during staging must not publish an incomplete result.
 testthat::local_mocked_bindings(write_csv=function(...)stop('simulated write failure'),.package='readr')
 testthat::expect_error(run_category_diagnostics(source,file.path(parent,'failed'),FALSE,root),'simulated')
 testthat::expect_false(file.exists(file.path(parent,'failed')))
 testthat::expect_length(list.files(parent,all.files=TRUE,pattern='^[.]diagnostics-'),0L)
})
