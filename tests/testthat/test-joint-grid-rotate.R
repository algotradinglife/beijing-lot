source(file.path('..','..','r','joint_win_scale.R'))
source(file.path('..','..','r','joint_grid_rotate.R'))
test_that('rotation opens diverse sleeves before depth, then copies, under caps', {
 cut<-list(cutoff_kind='DECISION_EPOCH',cutoff_identity='x',cutoff_ts='2020-01-01T00:00:00Z',target_issue='1',historical_admission=FALSE,model_receipt_sha256='m')
 t<-tibble::tibble(issue='1',ticket_id=letters[1:6],sleeve_id=rep(1:3,each=2),cell=rep(c('bad','good','good'),each=2),prob=c(.8,.7,.6,.5,.4,.3),payout_hat=200,base_copies=c(1L,1L,0L,0L,0L,0L))
 m<-tibble::tibble(sleeve_id=rep(1:3,each=2),fixture=c('a','b','c','d','e','f'))
 s<-tibble::tibble(issue='1',cell=c('bad','good'),return_ratio=c(.6,1.4),long_return_ratio=NA_real_,supported=TRUE,long_hit_signal='READY')
 attr(s,'input_receipt')<-list(cutoff=cut,hash=digest::digest(s,algo='sha256'))
 a<-joint_grid_rotate(t,m,s,cut,'m','EXPAND',FALSE,2,2,8,128,8,1,.5,.8,1.2,4)
 expect_equal(a$copies,c(1,1,1,0,1,0))
 b<-joint_grid_rotate(t,m,s,cut,'m','ROTATE',FALSE,2,2,8,128,8,1,.5,.8,1.2,4)
 expect_equal(b$copies,c(1,0,1,1,1,0));expect_equal(b$action[2],'REMOVED')
 c<-joint_grid_rotate(t,m,s,cut,'m','EXPAND',FALSE,2,2,16,128,8,1,.5,.8,1.2,8)
 expect_equal(c$copies,c(1,1,2,2,1,1))
 low<-joint_grid_rotate(t,m,s,cut,'m','EXPAND',FALSE,2,2,16,256,8,1,.5,.8,1.2,8)
 expect_equal(low$copies,t$base_copies)
 cap<-joint_grid_rotate(t,m,s,cut,'m','EXPAND',FALSE,2,2,16,128,2,1,.5,.8,1.2,8)
 expect_equal(cap$copies,c(1,1,1,0,1,0))
 mm<-m;mm$fixture[5:6]<-c('a','b')
 overlap<-joint_grid_rotate(t,mm,s,cut,'m','EXPAND',FALSE,2,2,8,128,8,1,.5,.8,1.2,4)
 expect_equal(overlap$copies,c(1,1,1,1,0,0))
 u<-t;u$future_label<-1e9
 expect_identical(joint_grid_rotate(u,m,s,cut,'m','EXPAND',FALSE,2,2,8,128,8,1,.5,.8,1.2,4),a)
 bad<-cut;bad$target_issue<-'2';expect_error(joint_grid_rotate(t,m,s,bad,'m','EXPAND',FALSE,2,2,8,128,8,1,.5,.8,1.2,4))
 expect_error(joint_grid_rotate(t,m,s,cut,'m','EXPAND',FALSE,2,2,8,128,8,1,.5,.8,1.2,5))
 expect_error(joint_grid_rotate(t,m[-1,],s,cut,'m','EXPAND',FALSE,2,2,8,128,8,1,.5,.8,1.2,4))
 empty<-t[FALSE,];em<-m[FALSE,]
 expect_equal(nrow(joint_grid_rotate(empty,em,s,cut,'m','EXPAND',FALSE,2,2,8,128,8,1,.5,.8,1.2,4)),0)
})
