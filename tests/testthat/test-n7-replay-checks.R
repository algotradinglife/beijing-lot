source('../../r/n7_replay_checks.R')
testthat::test_that('replay evidence fails closed on missing verdicts and partial scopes', {
 x<-data.frame(issue=c('01','02'),same=c(TRUE,TRUE))
 testthat::expect_true(n7_replay_checks(x,c('02','01'),'same'))
 testthat::expect_error(n7_replay_checks(x['issue'],c('01','02'),'same'))
 testthat::expect_error(n7_replay_checks(x,'01','same'))
 x$same<-c(TRUE,NA)
 testthat::expect_error(n7_replay_checks(x,c('01','02'),'same'))
 x$same<-c(TRUE,FALSE)
 testthat::expect_error(n7_replay_checks(x,c('01','02'),'same'))
 x$same<-c(1,1)
 testthat::expect_error(n7_replay_checks(x,c('01','02'),'same'))
 x$same<-c(TRUE,TRUE);x$issue<-c('01','01')
 testthat::expect_error(n7_replay_checks(x,c('01','02'),'same'))
})
