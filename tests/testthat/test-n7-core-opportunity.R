 b<-n7_core_partition(x,cut,cut,2,30,30,2,'VALUE',.15)
 expect_equal(a$core_ids,0:1);expect_equal(a$opportunity_ids,2L)
 expect_equal(b$opportunity_ids,3L);expect_equal(a$opportunity_stake_cny,30)
