source('../../r/fundamentals_drawdown_plot.R')
testthat::test_that('drawdown uses running peak and marks first maximum', {
 x <- tibble::tibble(model='A',policy='p',label='BASE',issue=c(NA,'001','002','003','004'),
  period=0:4,equity_cny=c(100,150,120,150,120),drawdown_cny=c(0,0,30,0,30))
 z <- strategy_drawdown_report(x[c(5,1,3,2,4),])
 testthat::expect_equal(z$rows$drawdown_percent,c(0,0,20,0,20))
 testthat::expect_equal(z$summary$max_drawdown_cny,30)
 testthat::expect_equal(z$summary$max_drawdown_percent,20)
 testthat::expect_equal(z$summary$max_cny_issue,'002')
 testthat::expect_equal(z$summary$current_drawdown_cny,30)
 built <- ggplot2::ggplot_build(z$plot)
 testthat::expect_equal(built$data[[2]]$y,-c(0,0,30,0,30))
 testthat::expect_equal(built$data[[3]]$x,2)
 y <- dplyr::mutate(x,policy='q',label='SINGLE75',equity_cny=c(100,200,200,200,150),drawdown_cny=c(0,0,0,0,50))
 testthat::expect_equal(strategy_drawdown_report(dplyr::bind_rows(x,y))$summary$max_drawdown_percent,c(20,25))
})
testthat::test_that('invalid ledger fails and zero drawdown is supported', {
 x <- tibble::tibble(model='A',policy='p',label='BASE',issue=c(NA,'001'),period=0:1,equity_cny=c(100,110),drawdown_cny=c(0,0))
 testthat::expect_equal(strategy_drawdown_report(x)$summary$max_drawdown_percent,0)
 testthat::expect_error(strategy_drawdown_report(x[0,]))
 testthat::expect_error(strategy_drawdown_report(dplyr::bind_rows(x,x)))
 bad<-x;bad$drawdown_cny[2]<-1;testthat::expect_error(strategy_drawdown_report(bad))
 bad<-x;bad$equity_cny[2]<-NA_real_;testthat::expect_error(strategy_drawdown_report(bad))
 bad<-x;bad$period[2]<-2;testthat::expect_error(strategy_drawdown_report(bad))
 bad<-x;bad$equity_cny[1]<-0;testthat::expect_error(strategy_drawdown_report(bad))
 bad<-x;bad$label[2]<-'changed';testthat::expect_error(strategy_drawdown_report(bad))
})
