testthat::test_that('joint grids use only prior labels and freeze a block', {
 root<-normalizePath('../..');core<-reticulate::import('src.temporal_learning.core');api<-reticulate::import('src.temporal_learning.frozen_blocks')
 f<-expand.grid(day=1:4,slot=1:2);f$issue<-sprintf('%06d',f$day);f$provider_id<-paste(f$issue,f$slot,sep='-')
 f$handicap<-0;f$q_W<-.5;f$q_D<-.2;f$q_L<-.3;f$p_D<-ifelse(f$slot==1,.1,.4)
 f$fixture_decision_ts<-sprintf('2011-01-%02dT00:00:00Z',f$day);f$last_fixture_cutoff<-f$fixture_decision_ts;f$day<-NULL
 labels<-f[c('issue','slot','provider_id')];labels$actual_direction<-ifelse(f$slot==2,'D','W')
 path<-tempfile(fileext='.csv');readr::write_csv(labels,path)
 targets<-subset(f,issue %in% c('000003','000004'));targets$issue_code<-targets$issue
 b<-api$frozen_block_schedule(reticulate::r_to_py(targets),cadence=2L)[[1]];c<-core$Cutoff$decision_epoch(b$fit_issue,b$fit_cutoff_ts)
 m<-strength_draw_ridge_fit(f,b,c,path,digest::digest(file=path,algo='sha256'),root,list(source=paste(rep('a',64),collapse='')),TRUE,10,12,2)
 t<-subset(f,issue=='000004');c4<-core$Cutoff$decision_epoch('000004','2011-01-04T00:00:00Z')
 z<-strength_draw_ridge_predict(m,t,c4,root)
 testthat::expect_true(z$D[2]>z$D[1]);testthat::expect_true(all(z$D>0 & z$D<1))
 testthat::expect_equal(z$W+z$D+z$L,c(1,1));testthat::expect_equal(z$W/z$L,c(5/3,5/3))
 testthat::expect_error(strength_draw_ridge_predict(m,t,c,root))
 testthat::expect_error(strength_draw_ridge_predict(m,transform(t,actual='D'),c4,root))
 bad<-m;bad$coefficients[]<-0;testthat::expect_error(strength_draw_ridge_predict(bad,t,c4,root))
 labels$actual_direction[labels$issue %in% c('000003','000004')]<-'L';readr::write_csv(labels,path)
 changed<-f;changed$last_fixture_cutoff[changed$issue %in% c('000003','000004')]<-'2010-01-01T00:00:00Z'
 mm<-strength_draw_ridge_fit(changed,b,c,path,digest::digest(file=path,algo='sha256'),root,list(source=paste(rep('a',64),collapse='')),TRUE,10,12,2)
 testthat::expect_equal(m$coefficients,mm$coefficients)
 testthat::expect_equal(z$D,strength_draw_ridge_predict(mm,t,c4,root)$D)
 testthat::expect_error(strength_draw_ridge_fit(transform(f,actual='D'),b,c,path,digest::digest(file=path,algo='sha256'),root,list(),TRUE,10,12,2))
})
testthat::test_that('report opens only forecast columns before saving predictions', {
 text<-readLines(file.path('..','..','quarto','193_strength_draw_ridge.qmd'))
 first<-grep("^x<-diagnostic_read_verified_csv",text)
 testthat::expect_length(first,1)
 testthat::expect_true(grepl('cols_only',text[first],fixed=TRUE))
 testthat::expect_false(grepl('actual_direction',text[first],fixed=TRUE))
 labels<-grep('^labels<-diagnostic_read_verified_csv',text)
 freezes<-grep('saveRDS(z,',text,fixed=TRUE)
 testthat::expect_true(length(labels)==1 && length(freezes)==1 && labels>freezes)
})

