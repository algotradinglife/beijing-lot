source(file.path('..','..','r','n7_fixture_price_diagnostic.R'))
testthat::test_that('fixture prices align exact identity and retain source evidence',{
 f<-tibble::tibble(issue='01',slot=1,provider_id='a',handicap=0,p_W=.5,p_D=.3,p_L=.2,q_W=.4,q_D=.3,q_L=.3)
 a<-tibble::tibble(issue='01',slot=1,provider_id='a',handicap=0,actual_direction='W',spf_sp=3,spf_source_sha256='hash',status='READY')
 z<-n7_fixture_price_diagnostic(f,a)
 testthat::expect_equal(z$estimated_sp,2.5);testthat::expect_equal(z$price_ratio,1.2)
 testthat::expect_equal(z$actual_p,.5)
 testthat::expect_equal(nrow(n7_fixture_price_diagnostic(f[0,],a)),0)
 testthat::expect_error(n7_fixture_price_diagnostic(f,a[0,]))
 testthat::expect_error(n7_fixture_price_diagnostic(f,dplyr::bind_rows(a,a)))
 b<-a;b$handicap<-1;testthat::expect_error(n7_fixture_price_diagnostic(f,b))
 b<-a;b$spf_source_sha256<-NA_character_;testthat::expect_error(n7_fixture_price_diagnostic(f,b))
 b<-f;b$q_W<-NA_real_;testthat::expect_error(n7_fixture_price_diagnostic(b,a))
})
