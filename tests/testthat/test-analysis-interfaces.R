testthat::test_that('typed queries reject schema loss and preserve missing and empty columns', {
  con <- DBI::dbConnect(RSQLite::SQLite(), ':memory:')
  on.exit(DBI::dbDisconnect(con), add=TRUE)
  p <- tibble::tibble(label=character(), n=integer())
  testthat::expect_identical(query_tibble(con, 'SELECT ? AS label, 2 AS n', p, list('00123')),
                           tibble::tibble(label='00123', n=2L))
  testthat::expect_identical(query_tibble(con, 'SELECT NULL AS label, NULL AS n', p),
                           tibble::tibble(label=NA_character_, n=NA_integer_))
  testthat::expect_identical(query_tibble(con, 'SELECT 1 AS label, 2 AS n WHERE 0', p), p)
  testthat::expect_error(query_tibble(con, 'SELECT 1 AS wrong', p), 'prototype')
  testthat::expect_error(query_tibble(con, "SELECT 'x' AS label, 1.5 AS n", p))
})

testthat::test_that('discovery summaries have identical schemas when empty and populated', {
  con <- DBI::dbConnect(RSQLite::SQLite(), ':memory:')
  on.exit(DBI::dbDisconnect(con), add=TRUE)
  DBI::dbExecute(con,'CREATE TABLE issue_slot_nowscore_map(issue_code TEXT, nowscore_provider_match_id TEXT)')
  DBI::dbExecute(con,'CREATE TABLE conflict_isolated_slot(isolation_reason TEXT)')
  DBI::dbExecute(con,'CREATE TABLE mapping_failure(issue_code TEXT)')
  empty <- discovery_summaries(con)
  testthat::expect_identical(empty$coverage$mapped_slots, 0L)
  testthat::expect_identical(empty$periods, tibble::tibble(period=character(), issues=integer(), slots=integer()))
  DBI::dbExecute(con,"INSERT INTO issue_slot_nowscore_map VALUES('120711','00123')")
  DBI::dbExecute(con,"INSERT INTO conflict_isolated_slot VALUES('void')")
  DBI::dbExecute(con,"INSERT INTO mapping_failure VALUES('120711')")
  populated <- discovery_summaries(con)
  testthat::expect_identical(lapply(empty, vctrs::vec_ptype), lapply(populated, vctrs::vec_ptype))
  testthat::expect_identical(populated$periods$slots, 1L)
  testthat::expect_identical(populated$failures$issue_code, '120711')
})

testthat::test_that('read-only helpers quote identifiers and release read connections', {
  root <- tempfile(); dir.create(root)
  dbdir <- file.path(root,'control','titan'); dir.create(dbdir, recursive=TRUE)
  db <- file.path(dbdir,'control.sqlite')
  con <- DBI::dbConnect(RSQLite::SQLite(), db)
  DBI::dbWriteTable(con, 'table with spaces', data.frame(x=1:2))
  DBI::dbWriteTable(con, 'settlement_merged', data.frame(issue='00123', sp=NA_real_))
  DBI::dbDisconnect(con)
  ro <- connect_titan(root)
  on.exit(DBI::dbDisconnect(ro), add=TRUE)
  testthat::expect_equal(sql_table_count(ro,'table with spaces'),2)
  testthat::expect_error(DBI::dbExecute(ro,'CREATE TABLE forbidden(x)'),'readonly')
  testthat::expect_equal(read_settlement(db)$issue,'00123')
  testthat::expect_true(is.na(read_settlement(db)$sp))
  testthat::expect_null(parse_json_column(NA_character_))
  testthat::expect_equal(parse_json_column('{"x":1}')$x,1)
  testthat::expect_match(snapshot_window_note(),'diagnostic')
  testthat::expect_error(connect_discovery(root))
  testthat::expect_false(dir.exists(file.path(root,'control','external_id_discovery')))
  withr::local_envvar(BEIJING_LOT_DATA_ROOT=root)
  testthat::expect_identical(beijing_data_root(),normalizePath(root))
})

testthat::test_that('snapshot bridge preserves timezone, nulls, keys, and receipts without writing', {
  project <- normalizePath(testthat::test_path('..','..'))
  python <- Sys.getenv('BEIJING_LOT_VENV_PYTHON')
  if (!nzchar(python)) python <- file.path(project,'.venv','bin','python')
  root <- tempfile(); dbdir <- file.path(root,'control','titan'); dir.create(dbdir, recursive=TRUE)
  db <- file.path(dbdir,'control.sqlite')
  con <- DBI::dbConnect(RSQLite::SQLite(),db)
  DBI::dbExecute(con,'CREATE TABLE historical_fixture_capture(batch_id TEXT, source_fixture_id TEXT)')
  DBI::dbExecute(con,'CREATE TABLE historical_fixture_observation(batch_id TEXT, kickoff_source_raw TEXT)')
  DBI::dbExecute(con,'CREATE TABLE historical_euro_1x2_quote(batch_id TEXT,company_source_id TEXT,bookmaker_source_name TEXT,record_source_id TEXT,ordinal INTEGER,home_odds REAL,draw_odds REAL,away_odds REAL,market_time_source_raw TEXT)')
  DBI::dbExecute(con,"INSERT INTO historical_fixture_capture VALUES('b','00123')")
  DBI::dbExecute(con,"INSERT INTO historical_fixture_observation VALUES('b','2010,1,2,12,30,00')")
  DBI::dbExecute(con,"INSERT INTO historical_euro_1x2_quote VALUES('b','1','Book','r',0,2.0,NULL,3.0,'2010,1,2,10,24,00')")
  DBI::dbDisconnect(con)
  before <- digest::digest(file=db,algo='sha256')
  long <- snapshot_long(root,project,python,fixture_ids='00123')
  testthat::expect_s3_class(long,'tbl_df')
  testthat::expect_true(all(long$fixture_id == '00123'))
  testthat::expect_true(all(is.na(long$draw_odds)))
  testthat::expect_equal(format(long$market_time[1],tz='UTC'), '2010-01-02 02:24:00')
  testthat::expect_identical(attr(long,'receipts')[[1]]$availability_policy,'HISTORICAL_PROXY')
  wide <- snapshot_wide(root,project,python,fixture_ids='00123')
  testthat::expect_equal(nrow(wide),1)
  testthat::expect_equal(wide$home_odds_final,2)
  testthat::expect_error(snapshot_long(root,project,python,fixture_ids='missing'),'absent')
  testthat::expect_equal(nrow(snapshot_long(root,project,python,fixture_ids=character())),0)
  empty_wide <- snapshot_wide(root,project,python,fixture_ids=character())
  testthat::expect_identical(names(empty_wide), names(wide))
  testthat::expect_type(empty_wide$home_odds_final, 'double')
  testthat::expect_s3_class(empty_wide$market_time_final, 'POSIXct')
  other_project <- tempfile(); dir.create(other_project)
  testthat::expect_error(project_python_module('src.titan_clean.snapshots', other_project, python), 'outside requested project root')
  testthat::expect_identical(digest::digest(file=db,algo='sha256'),before)
})
