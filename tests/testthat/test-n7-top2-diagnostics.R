source(file.path('..','..','r','n7_top2_diagnostics.R'))
testthat::test_that('paired group transfers reconcile money and isolate fixed depth', {
 r<-expand.grid(sleeve_id=c('a','b'),mode=c('PROB','SOFT','HARD','FULL'),stringsAsFactors=FALSE)
 r$issue<-'01';r$arm<-paste0('M_',r$mode);r$actual_top2<-r$sleeve_id=='a'
 r$actual_legal<-r$actual_top2 | r$mode %in% c('PROB','SOFT')
 r$actual_rank<-c(3,1,1,3,1,129,1,129)
 r$purchase_rank<-ifelse(r$actual_legal,r$actual_rank,NA_integer_)
 r$actual_gross_cny<-ifelse(r$sleeve_id=='a',100,40)
 f<-r |> dplyr::select(issue,arm,sleeve_id) |>
  dplyr::mutate(depth=ifelse(arm=='M_FULL',128,2),stake=2*depth)
 x<-n7_top2_diagnostics(r,f)
 soft<-x$flow[x$flow$mode=='SOFT',]
 testthat::expect_equal(soft$rescued_groups,1)
 testthat::expect_equal(soft$lost_groups,1)
 testthat::expect_equal(soft$third_lost_groups,1)
 testthat::expect_equal(soft$net_change,60)
 testthat::expect_equal(soft$stake_change,0)
 testthat::expect_equal(x$fixed_depth$gross_change,c(60,60))
 testthat::expect_equal(x$fixed_depth$stake,c(8,8))
 testthat::expect_false('FULL' %in% x$fixed_depth$mode)
 testthat::expect_equal(nrow(x$fixed_groups),4)
 testthat::expect_equal(sum(x$fixed_groups$fixed_gross),200)
 testthat::expect_equal(sum(x$fixed_groups$base_stake),16)
 testthat::expect_error(n7_top2_diagnostics(r[-1,],f))
 bad<-r;bad$actual_gross_cny[1]<-99
 testthat::expect_error(n7_top2_diagnostics(bad,f))
 testthat::expect_error(n7_top2_diagnostics(r,dplyr::mutate(f,stake=5)))
 empty<-n7_top2_diagnostics(r,f[0,])
 testthat::expect_equal(empty$flow$net_change,rep(0,4))
 testthat::expect_equal(nrow(empty$fixed_depth),0)
 testthat::expect_equal(nrow(empty$fixed_groups),0)
})

testthat::test_that('joint Top2 calibration fails on either unmatched side', {
 coverage<-tibble::tibble(issue=c('01','02'),arm='M_PROB',sleeve_id='a',top2_mass=c(.2,.4))
 ranks<-coverage |> dplyr::select(-top2_mass) |> dplyr::mutate(actual_top2=c(TRUE,FALSE))
 z<-n7_top2_joint_calibration(coverage,ranks,c(0,1))
 testthat::expect_equal(z$summary$groups,2L)
 testthat::expect_equal(z$summary$issues,2L)
 testthat::expect_equal(z$summary$predicted,.3)
 testthat::expect_equal(z$summary$observed,.5)
 testthat::expect_error(n7_top2_joint_calibration(coverage[-1,],ranks,c(0,1)))
 testthat::expect_error(n7_top2_joint_calibration(coverage,ranks[-1,],c(0,1)))
 testthat::expect_error(n7_top2_joint_calibration(dplyr::bind_rows(coverage,coverage),ranks,c(0,1)))
})
