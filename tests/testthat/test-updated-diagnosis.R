source('../../r/fundamentals_updated_diagnosis.R')

testthat::test_that('diagnosis reconciles roles, unique supports and payout', {
  f<-tibble::tibble(cohort='new100',issue='001',slot=1:5,provider_id=as.character(1:5),
    handicap=0,home='H',away='A',competition='League',actual='W',spf_sp=2,
    p_W=.6,p_D=.25,p_L=.15,q_W=.65,q_D=.2,q_L=.15)
  l<-tibble::tibble(cohort='new100',issue='001',policy='N5',group=1,slot=1:5,
    provider_id=as.character(1:5),role=c('A','A','D','D','C'),support=c('3','3','31','31','30'),hit=1)
  i<-tibble::tibble(cohort='new100',issue='001',policy='N5',stake=16,gross=41.6,net=25.6,groups=1,hits=1,status='COMPLETE')
  v<-updated_scope_diagnosis(f,l,i)
  testthat::expect_equal(v$payout$ROI_percent,160)
  testthat::expect_equal(v$payout$group_hit_percent,100)
  testthat::expect_equal(v$groups$n,5L)
  testthat::expect_equal(v$available$market_top1_hit,100)
  testthat::expect_equal(v$pools$anchors,5L)
  dw<-v$directions |> dplyr::filter(model=='market',handicap=='0',direction=='W')
  testthat::expect_equal(dw$selected_count,5L)
  testthat::expect_equal(dw$precision_percent,100)
  testthat::expect_equal(dw$recall_percent,100)
  testthat::expect_true(all(is.na(v$directions$precision_percent[v$directions$direction=='D'])))
  testthat::expect_equal(sum(v$pairs$n[v$pairs$handicap=='ALL']),10L)
  testthat::expect_true(all(v$handicap_accuracy$top1_percent==100))
  testthat::expect_error(updated_scope_diagnosis(dplyr::bind_rows(f,f),l,i))
  testthat::expect_error(updated_scope_diagnosis(f,dplyr::bind_rows(l,l),i))
  testthat::expect_error(updated_scope_diagnosis(f,l,dplyr::mutate(i,hits=0)))
  testthat::expect_error(updated_scope_diagnosis(dplyr::mutate(f,p_W=.9),l,i))
  f$actual[1]<-'L';l$hit[1]<-0;i$gross<-0;i$net<- -16;i$hits<-0
  f$spf_sp[1]<-NA_real_
  v<-updated_scope_diagnosis(f,l,i)
  testthat::expect_equal(v$failures$cause,'SINGLES_ONLY')
  testthat::expect_equal(v$failures$one_away,1L)
  f$actual[1]<-'W';l$hit[1]<-1
  testthat::expect_error(updated_scope_diagnosis(f,l,i))
  f$actual<-c('W','D','W','D','L');l$hit<-c(1,0,1,1,1)
  v<-updated_scope_diagnosis(f,l,i)
  dw<-v$directions |> dplyr::filter(model=='market',handicap=='ALL',direction=='W')
  dd<-v$directions |> dplyr::filter(model=='market',handicap=='ALL',direction=='D')
  testthat::expect_equal(dw$hits,2L)
  testthat::expect_equal(dw$precision_percent,40)
  testthat::expect_true(all(v$handicap_accuracy$top1_percent==40))
  testthat::expect_equal(dw$recall_percent,100)
  testthat::expect_equal(dd$top2_recall_percent,100)
  testthat::expect_equal(dd$recall_percent,0)
  testthat::expect_true(is.na(dd$precision_percent))
  f$q_W[c(2,3,5)]<-c(.2,.1,.1);f$q_D[c(2,3,5)]<-c(.6,.2,.2);f$q_L[c(2,3,5)]<-c(.2,.7,.7)
  v<-updated_scope_diagnosis(f,l,i)
  overlap<-v$overlap |> dplyr::filter(play=='Top1',handicap=='ALL',actual=='ALL')
  testthat::expect_equal(unlist(overlap[c('both','baseline_only','market_only','neither')]),c(both=1,baseline_only=1,market_only=2,neither=1))
  testthat::expect_equal(overlap$n,5L)
  testthat::expect_equal(sum(unlist(overlap[grep('_percent$',names(overlap))])),100)
  testthat::expect_equal(nrow(v$overlap_fixtures),10L)
  dc<-v$draw_calibration |> dplyr::filter(handicap=='ALL')
  testthat::expect_equal(sum(dc$n),5L)
  testthat::expect_equal(sum(dc$draws),2L)
  testthat::expect_equal(sum(dc$predicted_draws),sum(f$q_D))
  testthat::expect_equal(sum(dc$top2_hits),4L)
  testthat::expect_true(all(is.na(dc$top2_percent[dc$n==0])))
  bd<-v$baseline_draw_calibration |> dplyr::filter(handicap=='ALL')
  testthat::expect_equal(sum(bd$n),5L)
  testthat::expect_equal(sum(bd$draws),2L)
  testthat::expect_equal(sum(bd$top2_hits),4L)
  testthat::expect_equal(sum(bd$predicted_draws),sum(f$p_D))
  testthat::expect_equal(bd$gap_pp[bd$n>0],40-25)
  testthat::expect_true(all(is.na(dc$actual_percent[dc$n==0])))
  fine<-v$draw_calibration_fine |> dplyr::filter(handicap=='ALL')
  testthat::expect_equal(sum(fine$n),5L)
  testthat::expect_equal(sum(fine$draws),2L)
  # q_D=.2 is admitted to [.2,.22), not the lower residual bucket.
  testthat::expect_equal(fine$n[as.character(fine$band)=='[0.2,0.22)'],4L)
  f$q_D<-c(0,.2,.22,.3,1);f$q_W<-(1-f$q_D)/2;f$q_L<-f$q_W
  edge<-updated_scope_diagnosis(f,l,i)$draw_calibration_fine |> dplyr::filter(handicap=='ALL')
  testthat::expect_equal(edge$n[as.character(edge$band)=='[0.22,0.24)'],1L)
  testthat::expect_equal(edge$n[as.character(edge$band)=='[0.3,1]'],2L)
  testthat::expect_equal(sum(edge$n),5L)
  endpoints<-c(0,.05,.1,.15,.2,.25,.3,.35,.4,1)
  for (j in seq_along(endpoints)) {
    f$q_D<-endpoints[j];f$q_W<-(1-f$q_D)/2;f$q_L<-f$q_W
    edge<-updated_scope_diagnosis(f,l,i)$draw_calibration |> dplyr::filter(handicap=='ALL')
    testthat::expect_equal(which(edge$n>0),min(j,9L))
    f$p_D<-endpoints[j];f$p_W<-(1-f$p_D)/2;f$p_L<-f$p_W
    edge<-updated_scope_diagnosis(f,l,i)$baseline_draw_calibration |> dplyr::filter(handicap=='ALL')
    testthat::expect_equal(which(edge$n>0),min(j,9L))
  }
})
