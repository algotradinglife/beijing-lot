testthat::test_that("draw54 review replays margin geometry, evidence and full controls", {
  root <- rprojroot::find_root(rprojroot::has_file("AGENTS.md"))
  out <- tempfile("draw54-"); log <- tempfile()
  status <- system2("/opt/R/4.6.1/bin/Rscript", shQuote(c(file.path(root, "r/fm17_draw54_review.R"), root, out)),
    env = paste0("R_LIBS=", shQuote(paste(.libPaths(), collapse = ":"))), stdout = log, stderr = log)
  testthat::expect_equal(status, 0L, info = paste(readLines(log), collapse = "\n"))
  all <- readr::read_csv(file.path(out, "all_fixtures.csv"), show_col_types = FALSE)
  c <- readr::read_csv(file.path(out, "cases54.csv"), show_col_types = FALSE)
  m <- readr::read_csv(file.path(out, "case_margins.csv"), show_col_types = FALSE)
  controls <- readr::read_csv(file.path(out, "controls.csv"), show_col_types = FALSE)
  ah <- readr::read_csv(file.path(out, "asian_alignment.csv"), show_col_types = FALSE)
  forms <- readr::read_csv(file.path(out, "case_forms.csv"), show_col_types = FALSE)
  review <- readr::read_csv(file.path(out, "case_review.csv"), show_col_types = FALSE)
  testthat::expect_equal(nrow(all), 345)
  testthat::expect_equal(sum(all$final_draw_third), 197)
  testthat::expect_equal(nrow(c), 54)
  testthat::expect_false(anyDuplicated(c$fixture_id) > 0)
  testthat::expect_equal(sum(c$handicap == 0), 17)
  testthat::expect_equal(sum(c$handicap != 0), 37)
  testthat::expect_equal(sum(c$line_is_mode), 27)
  testthat::expect_true(all(c$margin_top2))
  testthat::expect_equal(sum(c$within_half_goal_mean), 45)
  testthat::expect_true(all(c$line_is_mode[c$handicap == 0]))
  testthat::expect_true(all(abs(c$line_probability - c$p3) < 1e-10))
  testthat::expect_true(all(abs(all$left_probability + all$right_probability + all$line_probability - 1) < 1e-8))
  testthat::expect_equal(nrow(forms), 108)
  testthat::expect_equal(nrow(review), 54)
  testthat::expect_true(all(nzchar(review$fundamental_note)))
  testthat::expect_equal(nrow(ah), 48)
  testthat::expect_true(all(abs(ah$line_minus_asian_center) <= .5))
  for (d in unique(controls$dimension)) {
    z <- dplyr::filter(controls, dimension == d)
    testthat::expect_equal(sum(z$n), 197)
    testthat::expect_equal(sum(z$missed_draws), 54)
  }
  mass <- m |> dplyr::group_by(fixture_id, distribution) |>
    dplyr::summarise(mass = sum(probability), .groups = "drop")
  testthat::expect_true(all(abs(mass$mass - 1) < 1e-8))
  line <- m |> dplyr::filter(distribution == "final", relative_margin == 0) |>
    dplyr::left_join(c |> dplyr::select(fixture_id, line_probability), by = "fixture_id", relationship = "one-to-one")
  testthat::expect_equal(line$probability, line$line_probability, tolerance = 1e-12)
  r <- jsonlite::fromJSON(file.path(out, "receipt.json"))
  testthat::expect_equal(r$sample$article_rows_cases, 0)
  testthat::expect_equal(length(names(r$output_hashes)), 11L)
  for (n in names(r$output_hashes)) testthat::expect_equal(
    digest::digest(file = file.path(out, paste0(n, ".csv")), algo = "sha256"), r$output_hashes[[n]])
  # Key audited case: ordinary draw, central atom, final expected goals ~3.11.
  a <- dplyr::filter(c, fixture_id == "26098:104")
  testthat::expect_true(a$line_is_mode)
  testthat::expect_equal(a$line_probability, .2773788384205563, tolerance = 1e-10)
  testthat::expect_equal(a$before_expected_total, 3.112672742577782, tolerance = 1e-8)
})
