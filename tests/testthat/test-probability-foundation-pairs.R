source('../../r/strategy_diagnostic_probabilities.R')
source('../../r/probability_foundation_pairs.R')
testthat::test_that('paired evaluation separates confidence from actual probability and fixed sets', {
 x<-tidyr::expand_grid(issue='001',slot=1L,provider_id='0001',model=c('A','B'),outcome=c('W','D','L')) |>
  dplyr::mutate(actual_outcome='D',stage='ONE',probability=c(.5,.3,.2,.6,.15,.25))
 z<-probability_foundation_pairs(x,'A','stage',c('W','D','L'),c(0,.5,1),1e-12)
 testthat::expect_equal(z$pairs$actual_probability_delta,-.15)
 testthat::expect_equal(z$pairs$top1_mass_delta,.1)
 testthat::expect_equal(z$pairs$top2_mass_delta,.05)
 testthat::expect_equal(z$pairs$baseline_top2_mass_delta,-.05)
 testthat::expect_true(z$pairs$top2_lost)
 testthat::expect_equal(z$pairs$log_loss_delta,log(2))
 testthat::expect_identical(z$pairs$issue,'001')
 testthat::expect_identical(z$pairs$provider_id,'0001')
 testthat::expect_equal(z$summary$down,1)
 testthat::expect_error(probability_foundation_pairs(x,'X','stage',c('W','D','L'),c(0,1),0))
 testthat::expect_error(probability_foundation_pairs(x,'A','stage',c('W','D','L'),c(0,1),NA_real_))
 x$probability[4:6]<-c(.5,.3,.2)
 z<-probability_foundation_pairs(x,'A','stage',c('W','D','L'),c(0,1),0)
 testthat::expect_equal(z$summary$unchanged,1)
 testthat::expect_false(z$pairs$top2_changed)
 x$probability[4:6]<-c(1,0,0)
 z<-probability_foundation_pairs(x,'A','stage',c('W','D','L'),c(0,1),0)
 testthat::expect_identical(z$pairs$log_loss,Inf)
 testthat::expect_equal(z$pairs$excluded_outcome,'L')
})
