source(file.path('..','..','r','strength_draw_blend.R'))
testthat::test_that('draw blend preserves market direction and rejects invalid clocks or labels', {
 core<-reticulate::import('src.temporal_learning.core')
 f<-data.frame(issue='001',slot=1L,provider_id='002',handicap=-1,
  cutoff_ts='2010-01-01T00:00:00Z',fixture_decision_ts='2010-01-01T01:00:00Z',q_W=.5,q_D=.2,q_L=.3,p_D=.4)
 c<-core$Cutoff$decision_epoch('001',f$cutoff_ts)
 z<-strength_draw_blend(f,c,c(0,.25,.5,1))
 testthat::expect_error(strength_draw_blend(f[,setdiff(names(f),'fixture_decision_ts')],c,.25))
 testthat::expect_error(strength_draw_blend(transform(f,fixture_decision_ts=NA_character_),c,.25))
 testthat::expect_equal(z$D,c(.2,.25,.3,.4))
 testthat::expect_equal(z$W/z$L,rep(5/3,4))
 testthat::expect_equal(z$W+z$D+z$L,rep(1,4))
 testthat::expect_error(strength_draw_blend(transform(f,actual='D'),c,.25))
 testthat::expect_error(strength_draw_blend(f,core$Cutoff$decision_epoch('002',f$cutoff_ts),.25))
 testthat::expect_error(strength_draw_blend(transform(f,fixture_decision_ts='2009-01-01T00:00:00Z'),c,.25))
 testthat::expect_error(strength_draw_blend(transform(f,p_D=1.1),c,.25))
 testthat::expect_error(strength_draw_blend(f,c,1.1))
 testthat::expect_error(strength_draw_blend(rbind(f,f),c,.25))
})
