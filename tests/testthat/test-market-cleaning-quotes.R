source(file.path(if (dir.exists("r")) "." else "../..", "r/market_cleaning_quotes.R"))
testthat::test_that("quote examples retain numeric odds and verify snapshots", {
  study <- tempfile(); dir.create(study)
  row <- list(issue="110509",slot=1L,provider_id="123",market="euro",
              status="QUOTES_PRIOR_DIAGNOSTIC",rows=list(list(company="A",odds_W=2.1)))
  path <- file.path(study,"110509.json")
  jsonlite::write_json(list(row),path,auto_unbox=TRUE)
  summary <- list(issues=list(list(issue="110509")),output_hashes=list())
  summary$output_hashes[["110509.json"]] <- digest::digest(file=path,algo="sha256")
  sp <- file.path(study,"summary.json"); jsonlite::write_json(summary,sp,auto_unbox=TRUE)
  hash <- digest::digest(file=sp,algo="sha256")
  result <- read_market_quote_examples(study,hash)
  testthat::expect_equal(nrow(result),1L)
  testthat::expect_equal(result$quotes[[1]][[1]]$odds_W,2.1)
  testthat::expect_error(read_market_quote_examples(study,"bad"),"Summary hash")
  testthat::expect_error(read_market_quote_examples(study,hash,0))
  writeLines("[]",path)
  testthat::expect_error(read_market_quote_examples(study,hash),"Issue output hash")
  unlink(study,recursive=TRUE)
})
