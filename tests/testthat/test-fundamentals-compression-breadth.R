testthat::test_that('paired ex-largest and ordered capital risks use issue observations', {
 x <- tibble::tibble(partition='TEST',issue=sprintf('1001%02d',1:6),policy='B',stake=256,gross=c(0,0,1000,0,0,0),net=gross-stake,hits=as.integer(gross>0),groups=1L,status='COMPLETE',model_union=.3,model_union_se=.01,model_proxy_net=0,budget_cny=256,depth=0L,rule='TOP1',breadth='REPEAT',compression_seed=0L,breadth_seed=0L,unique_tickets=128L,paid_ticket_units=128L,repeat_units=0L,miss_distance=as.integer(hits==0),fixture_hhi=1/7,outcome_hhi=1/14,max_pair_overlap=0L,max_single_groups=0L)
 y <- dplyr::mutate(x,policy='C',gross=gross+c(0,0,1000,0,0,0),net=gross-stake,model_union=.4)
 z <- compression_breadth_summary(dplyr::bind_rows(x,y),'B',100000)
 a <- dplyr::filter(z$summary,policy=='C')
 testthat::expect_equal(a$matched_lift,1000)
 testthat::expect_equal(a$ex_largest_lift,0)
 testthat::expect_equal(a$ex_largest_net,-1280)
 testthat::expect_equal(a$ex_largest_roi,-1)
 testthat::expect_equal(a$longest_losing_run,3L)
 testthat::expect_equal(a$max_drawdown_duration,3L)
 testthat::expect_true(a$unrecovered_at_end)
 testthat::expect_equal(a$ending_capital,100464)
 testthat::expect_equal(a$payout_hhi,1)
 testthat::expect_equal(a$union_lift,.1)
 testthat::expect_equal(a$ex_largest_year_issues,0L)
 testthat::expect_true(is.na(a$ex_largest_year_net))
 testthat::expect_true(is.na(a$worst_10_loss))
 testthat::expect_error(compression_breadth_summary(y,'B',100000))
 testthat::expect_error(compression_breadth_summary(dplyr::bind_rows(x,x),'B',100000))
})
testthat::test_that('fixed descriptive strata retain denominators and reject uncovered bins', {
 x <- tibble::tibble(issue=c('100101','100102'),slot=1L,partition='TEST',policy='A',single=TRUE,covered=c(TRUE,FALSE),retention=c(.6,.8),p2=c(.3,.1),gap=c(.1,.5),entropy=c(1,.5),divergence=c(.1,.2),handicap=c(-1,0),top1_direction=c('W','D'))
 y <- compression_leg_strata(x,list(retention=c(-Inf,.7,Inf)))
 testthat::expect_equal(sum(y$holdings[y$variable=='retention']),2L)
 testthat::expect_equal(sort(y$hit_rate[y$variable=='retention']),c(0,1))
 testthat::expect_equal(nrow(compression_leg_strata(x[0,],list(retention=c(-Inf,Inf)))),0L)
 testthat::expect_error(compression_leg_strata(x,list(retention=c(.7,1))))
 testthat::expect_error(compression_leg_strata(x,list(retention=c(1,0))))
})
