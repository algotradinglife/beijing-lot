source(file.path('..','..','r','third_outcome_diagnostics.R'))
testthat::test_that('shared fixtures produce joint rather than independent group risk', {
 a<-tibble::tibble(model='M',issue='01',sleeve_id='a',slot=1:7,provider_id=as.character(1:7),p3=.2,third_hit=c(TRUE,rep(FALSE,6)))
 b<-dplyr::mutate(a,sleeve_id='b')
 z<-third_outcome_group_risk(dplyr::bind_rows(a,b))
 mu<-.8^7
 testthat::expect_equal(z$issues$expected_all_top2,2*mu)
 testthat::expect_equal(z$issues$independent_groups_variance,2*mu*(1-mu))
 testthat::expect_equal(z$issues$shared_fixtures_variance,4*mu*(1-mu))
 testthat::expect_equal(z$issues$actual_thirds,1)
 testthat::expect_equal(z$issues$group_third_exposures,2)
 testthat::expect_equal(z$issues$groups_with_third,2)
 testthat::expect_equal(z$issues$max_third_fanout,2)
 b$slot<-8:14;b$provider_id<-as.character(8:14)
 zz<-third_outcome_group_risk(dplyr::bind_rows(a,b))
 testthat::expect_equal(zz$issues$shared_fixtures_variance,zz$issues$independent_groups_variance)
 testthat::expect_error(third_outcome_group_risk(a[-1,]))
 testthat::expect_error(third_outcome_group_risk(dplyr::bind_rows(a,a)))
 b<-dplyr::mutate(a,sleeve_id='b',p3=.3)
 testthat::expect_error(third_outcome_group_risk(dplyr::bind_rows(a,b)))
 testthat::expect_error(third_outcome_group_risk(a[0,]))
})
