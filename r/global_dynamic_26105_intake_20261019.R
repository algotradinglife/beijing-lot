# Explicit published versions, immutable factual intake; no network or fitting.
args <- commandArgs(TRUE)
if(length(args)!=5L) stop('Exactly ROOT BASE_PUBLICATION EURO_PUBLICATION ROSTER OUTPUT_TOKEN required')
root <- normalizePath(args[1],mustWork=TRUE)
paths <- normalizePath(args[2:4],mustWork=TRUE)
input_bytes <- lapply(paths,function(path) readBin(path,'raw',n=file.info(path)$size))
input_hashes <- vapply(input_bytes,digest::digest,character(1),algo='sha256',serialize=FALSE)
base <- jsonlite::fromJSON(rawToChar(input_bytes[[1]]),simplifyVector=FALSE)
euro <- jsonlite::fromJSON(rawToChar(input_bytes[[2]]),simplifyVector=FALSE)
roster <- jsonlite::fromJSON(rawToChar(input_bytes[[3]]),simplifyVector=FALSE)
if(!identical(base$publication$dataset,'source_issue_26105') || !identical(euro$publication$dataset,'source_euro_issue_26105')) stop('Exact26105 published dataset identities required')
checkmate::assert_string(base$publication$version,min.chars=1L)
checkmate::assert_string(euro$publication$version,min.chars=1L)
client_path <- file.path(root,'r/global_dynamic_26105_intake_20261019.R')
client_sha <- digest::digest(file=client_path,algo='sha256')
if(length(roster$data)!=365L) stop('Exact365-fixture roster required')
stopifnot(base$receipt$expected_slots==365L,euro$receipt$expected_slots==365L,
 base$receipt$network_attempts==0L,euro$receipt$network_attempts==0L,
 base$roster_input_sha256==input_hashes[3],
 euro$roster_input_sha256==input_hashes[3])
suppressPackageStartupMessages(library(tidyverse));library(beidan)
invisible(python_backend(file.path(root,'.venv/bin/python')))
backend <- reticulate::import('beidan_backend.catalog.paths',convert=FALSE)
out <- reticulate::py_str(backend$location(args[5],require_exists=FALSE))
if(dir.exists(out)) stop('Immutable intake output exists')
versions <- list(fundamentals=base$publication$version,euro=euro$publication$version)
f <- list()
for(name in c('match','history','provenance','fixture_schedule','resources','coverage'))
 f[[name]] <- read_dataset('source_issue_26105',name,version=versions$fundamentals)
r <- bind_rows(map(roster$data, ~ .x[c('issue_id','slot','league','handicap')])) |> transmute(fixture_id=paste0(issue_id,':',slot),slot,league,handicap)
stopifnot(nrow(r)==365L,!anyDuplicated(r$fixture_id),setequal(r$fixture_id,paste0('26105:',seq_len(365L))))
fixtures <- f$match |> left_join(r,by='fixture_id',relationship='one-to-one') |> mutate(cutoff_utc=kickoff_at-lubridate::hours(24))
stopifnot(nrow(fixtures)==365L,!anyDuplicated(fixtures$fixture_id),setequal(fixtures$fixture_id,r$fixture_id),!anyNA(fixtures[c('provider_id','home_id','away_id','handicap')]),identical(is.na(fixtures$kickoff_at),is.na(fixtures$cutoff_utc)))
fixtures <- fixtures |> mutate(temporal_state=if_else(is.na(kickoff_at),'UNRESOLVED_KICKOFF','ELIGIBLE_T24'))
contexts <- read_dataset('source_euro_issue_26105','contexts',version=versions$euro)
bindings <- set_names(as.list(input_hashes),c('base_publication','euro_publication','roster'))
input <- list(issue_id='26105',fixtures=fixtures,history=f$history,provenance=f$provenance,fixture_schedule=f$fixture_schedule,contexts=contexts,resources=f$resources,source_versions=versions,input_bindings=bindings)
stopifnot(identical(unname(map_chr(paths,~digest::digest(file=.x,algo='sha256'))),unname(input_hashes)),client_sha==digest::digest(file=client_path,algo='sha256'))
dir.create(out,recursive=TRUE)
text <- jsonlite::toJSON(input,dataframe='rows',auto_unbox=TRUE,na='null',digits=NA,POSIXt='ISO8601')
writeLines(text,file.path(out,'inputs.json'),useBytes=TRUE)
jsonlite::write_json(list(input_sha256=digest::digest(file=file.path(out,'inputs.json'),algo='sha256'),source_versions=versions,input_bindings=bindings,
 client_sha256=client_sha,historical_admission=FALSE,model_admission=FALSE),file.path(out,'intake-receipt.json'),auto_unbox=TRUE,pretty=TRUE)
print(tibble(fixtures=nrow(fixtures),history=nrow(f$history),model_admission=FALSE))
