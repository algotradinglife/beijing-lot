# Native26102 estimates only; no target settlement or SP access.
root <- normalizePath(commandArgs(TRUE)[1],mustWork=TRUE)
out <- file.path(root,'results/fm15-26102-20261012')
implementation <- normalizePath(file.path(out,'implementation'),mustWork=TRUE)
suppressPackageStartupMessages(library(tidyverse));library(jsonlite)
library(beidan,lib.loc=file.path(root,'results/fm15-version-20261012/library'))
inv <- fromJSON(file.path(out,'implementation-inventory.json'))
stopifnot(inv$status=='RUN_BOUND_CURRENT_IMPLEMENTATION',inv$issue_id=='26102',all(map_chr(file.path(implementation,inv$files$path),~digest::digest(file=.x,algo='sha256'))==inv$files$sha256))
source(file.path(implementation,'packages/beidan/R/recent_venue_goals.R'),local=TRUE)
reticulate::use_python(file.path(root,'.venv/bin/python'),required=TRUE)
reticulate::import('sys',convert=FALSE)$path$insert(0L,file.path(implementation,'packages/beidan/inst/python'))
shared <- reticulate::import('beidan_backend.temporal_learning',convert=FALSE)
scope <- fromJSON(file.path(out,'scope.json'))
stopifnot(scope$model_id=='FM-1.5.0',scope$issue_id=='26102',!scope$new_run_target_settlement_opened)
paths <- c(scope$forecast_inputs$path,'results/fundamental-issues-20261011/inputs/rosters.rds','results/fm15-26102-20261012/implementation-inventory.json','r/fm15_26102_native.R')
hashes <- as.list(setNames(map_chr(file.path(root,paths),~digest::digest(file=.x,algo='sha256')),paths))
stopifnot(unlist(hashes[scope$forecast_inputs$path],use.names=FALSE)==scope$forecast_inputs$sha256)
parent <- readRDS(file.path(root,scope$forecast_inputs$path))
roster <- as_tibble(readRDS(file.path(root,paths[2]))[['26102']]$matches)
stopifnot(nrow(parent$fixtures)==86,!anyDuplicated(parent$fixtures$fixture_id))
hashes$DC_loaded_implementation <- beidan:::.score_margin_code(implementation)
policy <- list(recent_n=8L,alpha=.5,minimum_matches=12L,minimum_ess=8)
entries <- ledger <- fixtures <- list()
for(i in seq_len(nrow(parent$fixtures))) {
  f <- as.list(parent$fixtures[i,]);slot <- as.integer(sub('.*:','',f$fixture_id))
  r <- filter(roster,.data$slot==.env$slot);stopifnot(nrow(r)==1L,r$native_id==f$provider_id)
  if(is.na(f$cutoff_utc)) stop('Missing declared cutoff')
  h <- as_tibble(parent$history) |> filter(fixture_id==f$fixture_id) |> mutate(row_key=paste(scope,match_id,sep=':'),event_date=as.character(event_date))
  cutoff_text <- format(f$cutoff_utc,'%Y-%m-%dT%H:%M:%SZ',tz='UTC')
  z <- tryCatch(estimate_recent_venue_goals(h,f[c('fixture_id','issue_id','provider_id','home_id','away_id')],as.character(parent$fixtures$provider_id),shared$Cutoff$decision_epoch('26102',cutoff_text),hashes,implementation,policy,'HISTORICAL_DIAGNOSTIC'),error=identity)
  fixtures[[f$fixture_id]] <- list(fixture_id=f$fixture_id,provider_id_nowscore=f$provider_id,home_nowscore=f$home,away_nowscore=f$away,kickoff_at=format(f$cutoff_utc+lubridate::hours(24),'%Y-%m-%dT%H:%M:%SZ',tz='UTC'))
  if(inherits(z,'error')) {ledger[[f$fixture_id]]<-tibble(fixture_id=f$fixture_id,state='UNAVAILABLE',reason=conditionMessage(z));next}
  grid <- beidan:::dixon_coles_score_grid(z$parameters$lambda_home,z$parameters$lambda_away,handicap=0L,tail_tolerance=1e-10,rho=-.1)$grid |> as_tibble() |> select(home_goals,away_goals,probability)
  entries[[f$fixture_id]] <- list(fixture=f,roster=r,native=z,grid=grid,source_hashes=hashes)
  ledger[[f$fixture_id]] <- tibble(fixture_id=f$fixture_id,state='NATIVE_READY',reason='')
  message(f$fixture_id,' native ready')
}
batch <- list(entries=entries,ledger=bind_rows(ledger),policy=policy,source_hashes=hashes,implementation_inventory=inv)
id <- beidan:::.score_margin_hash(batch);path<-file.path(out,paste0('native-',substr(id,1,12),'.rds'))
if(file.exists(path))stopifnot(identical(readRDS(path),batch)) else saveRDS(batch,path)
write_json(list(native_file=basename(path),object_hash=id,sha256=digest::digest(file=path,algo='sha256')),file.path(out,'native-manifest.json'),auto_unbox=TRUE,pretty=TRUE)
write_csv(batch$ledger,file.path(out,'native-ledger.csv'))
write_json(unname(fixtures),file.path(out,'market-fixtures.json'),auto_unbox=TRUE,pretty=TRUE)
message('Native preparation complete: ',length(entries),' /86')
